--
-- `ai_messages.costUsd` — точная цена ответа в долларах, как её посчитал провайдер
-- (`cost_in_usd_ticks` в завершающем событии потока). Включает и токены, и вызовы поиска,
-- поэтому расход по чату считается сложением этих значений, а не оценкой по прайсу.
-- У вопросов человека и у ответов, сделанных до этой миграции, значения нет: провайдер отдаёт
-- стоимость только вместе с ответом, задним числом её взять неоткуда.
--
-- Модель по умолчанию меняется на `grok-4.20-0309-non-reasoning`: она не тратит токены на
-- «размышления». Замеры: на голом запросе к API разница с флагманом была шестнадцатикратной
-- ($0.0002 против $0.0032), а в нашем чате — примерно двукратной ($0.0013 против $0.003), потому
-- что системная подсказка и память дают одинаковый вход для обеих моделей, а флагман ещё и
-- дописывает reasoning-токены, которые оплачиваются как выходные. Плюс у дешёвой модели вдвое
-- больше контекст — миллион токенов против полумиллиона. Флагман остаётся в выборе шапки: его
-- берут для кода и сложных рассуждений, где разница в цене окупается качеством.
-- Уже созданные чаты сохраняют свою модель — меняется только значение для новых.

