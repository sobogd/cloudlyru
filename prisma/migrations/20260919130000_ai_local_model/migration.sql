-- Переход раздела «Чат» с xAI на локальную модель на маке.
--
-- Отвечать стала Gemma 4 E4B в LM Studio на домашнем маке, которая приходит на VPS через
-- reverse-SSH туннель (127.0.0.1:18812). Смысл переезда — не тратить токены на эксперименты:
-- модель локальная, поиск идёт через сервис на том же маке, и ответ не стоит ничего, кроме
-- времени (префилл ~300 токенов в секунду, генерация ~20).
--
-- Что меняется в БД:
--   1. Значение по умолчанию для модели новых чатов. Строка — идентификатор из LM Studio
--      (`GET /api/v0/models`), а не название файла на диске: смена кванта меняет его, поэтому
--      на проде это значение задаётся переменной `LLM_MODEL`, а здесь лежит то же самое.
--   2. Модель уже созданных чатов. У них записан идентификатор xAI (`grok-*`), которого в
--      LM Studio нет: на такой модели запрос отвечал бы «модель не найдена», и старые разговоры
--      стали бы нечитаемыми. Провайдера поменяли мы, а не владелец, поэтому старые чаты молча
--      переводятся на локальную модель — история сообщений при этом не трогается.
--
-- Компакция остаётся, но её содержимое меняется по смыслу: раньше `compactionBlob` был
-- непрозрачным зашифрованным блоком провайдера, теперь это обычная текстовая выжимка разговора,
-- которую пишет та же локальная модель и которая уходит в следующий запрос отдельным сообщением.
-- Колонки не меняются, но старые блоки xAI нечитаемы локальной моделью, поэтому вместе с
-- переводом чата сбрасывается и компакция: разговор начнётся заново от окна последних
-- сообщений, а сожмётся по порогу обычным путём.

-- AlterTable
ALTER TABLE "ai_chats" ALTER COLUMN "model" SET DEFAULT 'google/gemma-4-e4b';

-- Перевод уже созданных чатов на локальную модель со сбросом нечитаемой компакции
UPDATE "ai_chats"
SET "model" = 'google/gemma-4-e4b',
    "compactionId" = NULL,
    "compactionBlob" = NULL,
    "compactedUpToAt" = NULL
WHERE "model" LIKE 'grok%';
