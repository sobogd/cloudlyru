-- Лента почты ищет письмо условием `"box" = X OR X = ANY("alsoBoxes")`: письмо бывает сразу
-- в двух папках (отправленное себе, две копии у iCloud — см. комментарий у alsoBoxes в схеме).
-- Индекс ленты (userId, box, sortAt DESC, id DESC) покрывает только первую половину условия,
-- а по массиву Postgres без GIN перебирает строки пользователя. Массив короткий (0–1 элемент
-- в обычной жизни), поэтому индекс дешёвый и по размеру, и по стоимости записи.
CREATE INDEX "MailMessage_alsoBoxes_idx" ON "MailMessage" USING GIN ("alsoBoxes");
