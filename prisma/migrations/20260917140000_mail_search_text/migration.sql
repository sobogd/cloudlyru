-- Полнотекстовый поиск по почте.
--
-- Тело письма в БД до этой миграции не хранилось: в `bodyText` лежат первые 2000 символов
-- (превью для списка), а само письмо — сырой .eml в S3. Искать по телу, читая и разбирая
-- .eml на каждый запрос, нельзя: это десятки секунд и чтение всего архива. Поэтому текст
-- для поиска кладём в БД отдельной колонкой (`searchText` — заголовки и тело одним текстом),
-- а ищет по ней GIN-индекс.
--
-- `searchIndexedAt` — отметка «письмо проиндексировано». Письма, сохранённые до этой
-- миграции, её не имеют: их добирает фоновый бэкфилл (src/mail/mail-index.service.ts).
-- Без отметки проход брал бы одни и те же письма, которые не разбираются (нет объекта
-- в хранилище, битый .eml), и не двигался бы дальше.
ALTER TABLE "MailMessage" ADD COLUMN "searchText" TEXT;
ALTER TABLE "MailMessage" ADD COLUMN "searchIndexedAt" TIMESTAMP(3);

-- Индекс по выражению, а не по колонке: tsvector для письма в несколько килобайт весит
-- больше самого текста, и держать его копию в таблице незачем — он нужен только индексу.
-- Выражение (включая `coalesce`) обязано совпадать символ в символ с SEARCH_VECTOR_SQL
-- в src/mail/mail-search.service.ts: при расхождении индекс остаётся, но Postgres его
-- не узнаёт и поиск идёт перебором всех писем пользователя.
--
-- Конфигурация 'russian' одна на индекс и на запрос. Она глобит и латиницу
-- (invoice → invoic), но одинаково с обеих сторон, поэтому английские слова ищутся;
-- адреса и домены остаются цельными токенами (ivan@example.com).
CREATE INDEX "MailMessage_search_idx" ON "MailMessage"
  USING GIN (to_tsvector('russian', coalesce("searchText", '')));

-- Индекс под выборку бэкфилла. Частичный: как только проход закончится, в нём не останется
-- ни одной строки, и он не занимает места. Условие сортировки совпадает с запросом сервиса
-- (свежие письма первыми) — иначе индекс не использовался бы.
CREATE INDEX "MailMessage_search_backfill_idx" ON "MailMessage" ("sortAt" DESC)
  WHERE "searchIndexedAt" IS NULL;
