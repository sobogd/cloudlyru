-- Одна ожидающая задача на ассет и вид задачи.
--
-- Почему: enqueue() проверяет «нет ли уже задачи» отдельным SELECT, а потом создаёт строку.
-- Между проверкой и вставкой есть окно, и при двух одновременных вызовах (например, кнопку
-- «Дособрать превью» нажали дважды) обе проверки проходят — на один файл появляются две
-- задачи. Это видно в интерфейсе: «в очереди 95 028», хотя файлов без превью 58 489.
-- Конвертация в те же ключи S3 безвредна, но это часы работы впустую.
--
-- Сначала убираем уже накопившиеся дубли, оставляя самую раннюю задачу, затем ставим
-- частичный уникальный индекс: он закрывает гонку на уровне БД, а не на уровне проверки.
--
-- Индекс именно на state='pending', а не на pending+processing: PDF в конце задачи ставит
-- следующую задачу на остаток страниц, пока текущая ещё в processing, и это законно.
DELETE FROM "Job" a
USING "Job" b
WHERE a.state = 'pending'
  AND b.state = 'pending'
  AND a."assetId" = b."assetId"
  AND a.kind = b.kind
  AND (a."createdAt" > b."createdAt" OR (a."createdAt" = b."createdAt" AND a.id > b.id));

CREATE UNIQUE INDEX "Job_one_pending_per_asset_kind" ON "Job" ("assetId", "kind") WHERE state = 'pending';
