-- Компакция контекста: чтобы не платить за историю в каждом вопросе.
--
-- Каждый запрос несёт всю предыдущую переписку заново (API провайдера не помнит разговор:
-- мы храним историю сами и передаём её целиком). Значит, десятый вопрос в разговоре оплачивает
-- девять предыдущих — расход растёт квадратично, и на длинной переписке это дороже самого ответа.
--
-- Провайдер умеет сжимать разговор в один непрозрачный блок (`POST /v1/responses/compact`),
-- который затем передаётся вместо истории и разворачивается на его стороне. Блок храним у себя:
--   `compactionId`    — идентификатор сжатия (нужен вместе с блобом);
--   `compactionBlob`  — сам блок, непрозрачный: разбирать или править его нельзя, только
--                       передавать обратно целиком;
--   `compactedUpToAt` — до какого момента сообщения уже внутри блока. Всё, что создано позже,
--                       уходит в запрос обычными сообщениями.
-- Компакция вызывается по порогу (см. `COMPACT_AFTER_CHARS`) в фоне, чтобы не задерживать ответ:
-- сам вызов тоже стоит токенов и окупается только тогда, когда история иначе ушла бы ещё
-- несколько раз.

-- AlterTable
ALTER TABLE "ai_chats" ADD COLUMN     "compactedUpToAt" TIMESTAMP(3),
ADD COLUMN     "compactionBlob" TEXT,
ADD COLUMN     "compactionId" TEXT;
