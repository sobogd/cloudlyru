import '../data/queue_store.dart';
import '../section.dart';

/// Кандидат в очередь: файл, который надо выгрузить в конкретную облачную папку.
/// Отдельного типа для очереди намеренно нет — запись в базе отличается только состоянием,
/// а правила отбора работают с этим набором полей.
class Candidate {
  /// Все поля — снимок файла на момент обхода, ничего не вычисляется.
  const Candidate({
    required this.path,
    required this.relDir,
    required this.name,
    required this.size,
    required this.mtime,
    required this.section,
    required this.target,
  });

  /// Путь файла на телефоне: вместе с [target] — ключ строки очереди.
  final String path;

  /// Папка относительно родителя выбранной папки (см. DeviceFile.relDir): из неё в облаке
  /// собирается дерево. У «Фото» всегда пустая — медиатека лентой, а не деревом.
  final String relDir;

  /// Имя файла: под ним он и ляжет в облако (если имя не занято — см. UploadPlan.freeName).
  final String name;

  /// Размер и дата изменения на момент обхода. Это единственное, по чему здесь принимается
  /// решение «выгружать или нет»: считать хэш на этапе наполнения очереди — значит прочитать
  /// всю библиотеку целиком.
  final int size;
  final int mtime;

  /// Раздел, из которого пришёл файл: по нему уборка понимает, чьи строки трогать.
  final Section section;

  /// id облачной папки: у «Фото» — медиатека (плоско).
  final String target;
}

/// Строка очереди в том виде, в каком она нужна правилу уборки.
///
/// Раздел и состояние — типы, а не строки из базы: разбирает их [QueueStore] (там уже есть
/// оба перечисления), а правило уборки работает со значениями. Так переименование ключа
/// в перечислении не может молча отключить предохранитель, а незнакомое значение приходит
/// явным `null` и строку не убирает.
class QueueRow {
  /// Собирается из строки `queue`: id, путь, цель, раздел и состояние.
  const QueueRow(this.id, this.path, this.target, this.section, this.state);

  /// Первичный ключ строки `queue`: по нему строка и удаляется.
  final int id;

  final String path;
  final String target;

  /// Раздел строки или `null`, если значение в базе незнакомо (строка от другой версии
  /// приложения): чей это раздел — неизвестно, поэтому и убирать её нельзя.
  final Section? section;

  /// Состояние строки или `null` при незнакомом значении (см. [section]).
  final QueueState? state;
}

/// Что уже лежит в облаке: запись и слепок содержимого, по которому её выгружали.
class Uploaded {
  /// [entryId] — запись в облаке, [size] и [mtime] — слепок выгруженного файла.
  const Uploaded(this.entryId, this.size, this.mtime);

  /// id записи в облаке: по нему спрашивают метаданные файла и находят пару при правке из веба.
  final String entryId;

  /// Слепок выгруженного файла. Сравнивается с тем, что лежит на телефоне сейчас: совпали
  /// размер и дата — файл с прошлой выгрузки не менялся.
  final int size;
  final int mtime;
}

/// Ключ выгруженного: файл и облачная папка, в которую он лёг.
///
/// Равенство по паре полей нужно потому, что правила уборки работают с обычными Map и Set —
/// без базы и без строкового склеивания ключей.
class UploadedKey {
  /// [path] — файл на телефоне, [target] — облачная папка, в которую он лёг.
  const UploadedKey(this.path, this.target);

  final String path;
  final String target;

  /// Совпали и файл, и цель. Нужно, чтобы пара работала ключом Map/Set без базы.
  @override
  bool operator ==(Object other) =>
      other is UploadedKey && other.path == path && other.target == target;

  /// Хэш пары: без него ключ не годился бы для Set (см. `plan`, `obsolete`).
  @override
  int get hashCode => Object.hash(path, target);

  /// Строка «файл → папка»: попадает в отчёты и отладочный вывод.
  @override
  String toString() => '$path → $target';
}

/// Правила наполнения и уборки очереди. Чистые функции: всё, что зависит от диска и базы,
/// приходит аргументами, поэтому логику проверяют тесты без устройства (test/sync/
/// queue_planner_test.dart).
///
/// Пользуются ими [QueueBuilder] (что поставить в очередь) и [QueueStore.prune]
/// (что из неё убрать).
///
/// Хэш здесь не считается: очередь заполняется по размеру и дате изменения, иначе первый
/// проход по большой библиотеке читал бы все файлы целиком. Хэш нужен только в момент
/// выгрузки — для дедупа и для записи на сервере.
abstract final class QueuePlanner {
  /// Кого ставить в очередь: файл, которого нет в этой облачной папке, или тот, что изменился
  /// после выгрузки. Сравниваются размер и дата изменения — читать файлы на этапе наполнения
  /// очереди не нужно.
  ///
  /// Один и тот же файл из двух разделов даёт две записи с разными целями: папка может быть
  /// прикреплена и к «Файлам», и к «Фото», и тогда он нужен в обоих местах.
  ///
  /// Уже стоящий в очереди файл повторно в неё не попадает (в базе уникальность по паре
  /// «файл + цель»), поэтому проход можно запускать сколько угодно раз.
  static List<Candidate> plan(
    List<Candidate> candidates,
    Map<UploadedKey, Uploaded> uploaded,
  ) {
    final out = <Candidate>[];
    final seen = <UploadedKey>{};
    for (final candidate in candidates) {
      // один и тот же файл мог прийти в проход дважды (например, из двух корней обхода):
      // в базе на пару «файл + цель» одна строка, значит и в плане должна быть одна
      final key = UploadedKey(candidate.path, candidate.target);
      if (!seen.add(key)) continue;
      // запись о прошлой выгрузке есть и слепок совпал: содержимое в облаке то же самое
      final there = uploaded[key];
      final alreadyThere =
          there != null && there.size == candidate.size && there.mtime == candidate.mtime;
      if (alreadyThere) continue;
      out.add(candidate);
    }
    return out;
  }

  /// Что из очереди больше не подлежит выгрузке и должно быть убрано: папку отключили
  /// от раздела, файла на телефоне уже нет, или он больше не подходит. Без этой уборки
  /// очередь копила бы мусор от каждого изменения выбора папок.
  ///
  /// Разделы, которые в этом проходе не сканировались (например, цель ещё неизвестна —
  /// не выполнен вход), не трогаются вовсе: иначе одна неполадка выкосила бы всю очередь.
  /// Запущенная выгрузка тоже не трогается — файл в этот момент льётся. Строка с незнакомым
  /// разделом или состоянием (от другой версии приложения) остаётся: неизвестно ни чей она,
  /// ни не идёт ли по ней работа.
  static List<int> obsolete(
    List<QueueRow> rows,
    Set<UploadedKey> keep,
    Set<Section> scannedSections,
  ) =>
      rows
          .where((row) {
            // незнакомый раздел или состояние (строка от другой версии) не убираем:
            // непонятно, сканировался ли раздел в этом проходе и не идёт ли выгрузка
            final section = row.section;
            final state = row.state;
            return section != null &&
                state != null &&
                // раздел в этом проходе не проходили — его строки не наше дело
                scannedSections.contains(section) &&
                state != QueueState.running &&
                !keep.contains(UploadedKey(row.path, row.target));
          })
          .map((row) => row.id)
          .toList();

  /// Описывает ли слепок строки очереди (`size`/`mtime` в ней) тот же файл, что [candidate].
  ///
  /// Сравниваются размер и дата — то же, по чему решает [plan]: читать содержимое на этапе
  /// наполнения очереди нельзя. Правило нужно повторной постановке: если слепок совпал, файл
  /// с прошлого раза не менялся, и всё, что к слепку привязано (кэш хэша `queue.sha256`
  /// и `entry_id` прошлой выгрузки), остаётся верным. Не совпал — привязку надо сбросить:
  /// иначе кэш опишет прежнее содержимое, а по нему выгрузка решит, что файл уже в облаке
  /// (см. инвариант у `QueueItem.size`).
  static bool sameSnapshot({
    required int size,
    required int mtime,
    required Candidate candidate,
  }) => size == candidate.size && mtime == candidate.mtime;

  /// Готова ли строка к следующей попытке прямо сейчас.
  ///
  /// [state] — состояние строки, [attempts] — сколько раз её уже пробовали, [failedAt] —
  /// когда закончилась последняя попытка (null — «ещё не пробовали»), [now] — текущее время
  /// в миллисекундах.
  ///
  /// Ждём только строки с ошибкой: ожидающая строка — это либо новая, либо та, по которой
  /// человек нажал «повторить», и задерживать её нельзя. Остальные состояния выгрузку
  /// не начинают вовсе.
  static bool retryReady({
    required QueueState state,
    required int attempts,
    required int? failedAt,
    required int now,
  }) {
    if (state != QueueState.failed) return true;
    if (failedAt == null || attempts <= 0) return true;
    return now - failedAt >= retryPauseMs(attempts);
  }

  /// Пауза перед попыткой номер `attempts + 1`: минута, дальше вдвое, но не больше часа.
  ///
  /// Очередь сливается сторожем раз в минуту, и строка, которую сервер принципиально
  /// не принимает, без паузы ходила бы в сеть каждую минуту бесконечно. Час — предел:
  /// «забыть» такую строку нельзя, человек видит её в списке с текстом ошибки, а редкая
  /// попытка оставляет шанс, что причина ушла.
  static int retryPauseMs(int attempts) {
    const minute = 60 * 1000;
    const cap = 60 * minute;
    if (attempts <= 0) return 0;
    // attempts=1 → 1 мин, 2 → 2, 3 → 4, 4 → 8, 5 → 16, 6 и дальше → предел
    final shift = attempts > 6 ? 6 : attempts - 1;
    final pause = minute << shift;
    return pause > cap ? cap : pause;
  }
}
