/// Сколько отведено зеркалу за одно задание — **запасное** значение, если канал молчит.
///
/// Настоящее число живёт в Kotlin (`SyncJobService.PASS_BUDGET_MS`, там же предохранитель
/// задания `JOB_TIMEOUT_MS` = 9 минут и знание таймаута системы ~10 минут): фоновая точка
/// входа спрашивает его через канал (`BackgroundChannel.budgets`) и берёт это значение только
/// тогда, когда канал недоступен — движок поднят без моста, сборка не совпадает с нативной
/// частью. Числа обязаны совпадать: 9 − 2 (запас на очередь и ответ системе) = 7 минут.
///
/// Проход обязан закончиться раньше предохранителя, иначе движок уничтожат на середине работы.
/// Незаконченный проход не беда — сверка идемпотентна, остаток доедет следующим.
const int backgroundPassBudgetMs = 7 * 60 * 1000;

/// Дольше этого наполнять очередь в фоне не начинаем — тоже запасное значение
/// (в Kotlin `SyncJobService.QUEUE_DEADLINE_MS` = 6 минут). Очередь — подготовка, её догонит
/// приложение, а обход, оборванный системой на середине, только зря читает диск.
///
/// Считается от начала всего прохода, а не от конца зеркала: зеркало уже могло съесть свои
/// семь минут, и до конца задания остаётся около двух — обход папок в такой остаток не влез бы.
const int queueRefreshDeadlineMs = 6 * 60 * 1000;

/// Итог последнего фонового прохода: время и что вышло. Ключ свой, чтобы не смешивать его
/// с итогом прохода из приложения.
///
/// Пишется в базу зеркала (`MirrorStore.setMeta`) и **пока не читается никем**: единственное,
/// что доходит до человека от фоновой работы, — счётчики зеркала и `tokenError` в приложении,
/// а строка «что делал фон» в интерфейсе не показывается. Ключ оставлен и назван отдельно
/// именно затем, чтобы её было чем показать: это правка `sync_controller.dart` (владелец файла)
/// и экрана настроек. До тех пор запись живёт в базе как диагностический след — посмотреть
/// её можно через базу зеркала, а не через интерфейс.
const String keyBackgroundReport = 'bg_last_report';

/// Один фоновый проход, целиком: от проверок до ответа системе.
///
/// Порядок тот же, что у нативного клиента (`MirrorJobService`): сначала выясняем, есть ли
/// вообще чем работать, и только потом берёмся за диск и сеть. Если автоматика выключена
/// пользователем или токена устройства нет, задание тихо ничего не делает — это не ошибка.
///
/// [channel] — канал к службе: через него проход узнаёт про остановку ([BackgroundChannel.onCancel]
/// и `stopRequested`) и сообщает итог (`finished`).
///
/// ## Кто что делает: задание системы и приложение
///
/// Заданием занимается система (`JobScheduler` → `SyncJobService`): она решает, когда будить
/// процесс, поднимает отдельный движок Flutter с нашим мостом и запускает [syncBackgroundEntry].
/// Само приложение в это время может быть закрыто — его движка нет вовсе, и весь код ниже
/// выполняется в своём изоляте, со своими соединениями с базами.
///
/// Пока приложение на экране, работу делает его мгновенный режим (`mirror/mirror_live.dart`):
/// опрос головы журнала раз в 3 с (в фоне приложения — раз в 30 с) и проход по событию
/// файловой системы. Пересечения не допускают три проверки: `SyncJobService.onStartJob`
/// не поднимает движок, если приложение на экране; [_pass] проверяет то же самое ещё раз уже
/// внутри изолята; а `MirrorEngine._busy` не даёт двум проходам идти одновременно —
/// но только внутри одного изолята.
///
/// **Чего эти проверки не покрывают.** Признак «приложение на экране» (`AppPresence.foreground`)
/// неверен для свёрнутого, но живого приложения: его движок и `MirrorLive` продолжают работать
/// и по событию файловой системы запускают полноценный `engine.pass()`, а задание системы в это
/// же время поднимает второй движок. Тогда две сверки пишут в одни таблицы (свои соединения
/// с базой, `singleInstance: false`), дважды выгружают один файл и обе трогают предохранитель
/// массового удаления. Настоящее исключение должно быть общим для обоих изолятов — аренда
/// с таймстампом в базе зеркала или мьютекс в нативном мосте, — а не признак видимости;
/// альтернатива из ревью — запретить `MirrorLive` делать проходы, когда приложение не на экране,
/// оставив ему догон журнала. **Это правка чужих файлов** (`mirror/mirror_engine.dart`,
/// `mirror/mirror_live.dart`, `sync_controller.dart`) и отмечена как переданная их владельцу.
///
/// Что сделано на этой стороне: у скачивания теперь уникальное временное имя
/// (`SyncApi._writerTag`), поэтому два прохода не пишут в один и тот же файл и не портят
/// друг другу результат. Побочные эффекты самих проходов при этом остаются: работу они сделают
/// одну и ту же (сверка идемпотентна), но сходят в сеть и прочитают диск дважды.
///
/// Исключений не бросает: любая ошибка превращается в текст [note] и ответ `ok: false`.
/// Побочные эффекты: проход зеркала, обновление очереди, запись итога в базу зеркала и
/// сообщение в службу.
Future<void> runBackgroundPass(BackgroundChannel channel) async {
  var cancelled = false;
  channel.onCancel = () => cancelled = true;

  var ok = false;
  var note = '';
  try {
    // Остановку могли попросить, пока слушатель ещё не встал: у той стороны есть и флаг.
    cancelled = await channel.stopRequested();
    // Бюджеты задания спрашиваем у службы: она знает свой предохранитель и таймаут системы,
    // а наша копия чисел — только запасной вариант на случай молчащего канала
    final budgets = await channel.budgets();
    final result = await _pass(() => cancelled, budgets);
    ok = result.$1;
    note = result.$2;
  } catch (e) {
    // Сюда попадает всё, что не поймали внутри: проход обязан ответить службе, иначе она
    // будет ждать до предохранителя
    note = 'фоновый проход упал: $e';
  }

  _log(note);
  try {
    await channel.finished(ok: ok, note: note);
  } catch (e) {
    // Приложение могло закрыться вместе с движком: тогда отвечать уже некому, и это не беда.
    _log('итог не доставлен: $e');
  }
}

/// Содержание прохода: проверки, зеркало, очередь. Возвращает пару «успех» и текст для лога
/// и для памяти о проходе.
///
/// [cancelled] — проверка остановки, её спрашивают и перед зеркалом, и перед очередью: система
/// может отобрать задание в любой момент, и тогда новая работа не начинается.
/// [budgets] — бюджеты от службы (`BackgroundChannel.budgets`); `null` — канал молчит, берём
/// запасные значения из констант выше.
///
/// Исключений не бросает наружу: всё, что упало, попадает в текст, а не в прерванный проход.
/// Базы, открытые здесь, закрываются в `finally` — иначе соединения остались бы в процессе
/// до его конца.
Future<(bool, String)> _pass(
  bool Function() cancelled,
  ({int pass, int queue})? budgets,
) async {
  final passBudgetMs = budgets?.pass ?? backgroundPassBudgetMs;
  final queueDeadlineMs = budgets?.queue ?? queueRefreshDeadlineMs;
  final prefs = await SharedPreferences.getInstance();
  // Признак пишет приложение при входе и выходе; его отсутствие или `false` означает
  // «задание снято» — это нормальное состояние после выхода из аккаунта, а не ошибка
  if (prefs.getBool(BackgroundSync.keyEnabled) != true) {
    return (true, 'задание снято: ничего не делаю');
  }
  // Приложение на экране: там мгновенный режим, он замечает изменения за секунды, а наложенный
  // проход из фона спорил бы с ним за одни и те же базы (движок держит замок «один проход за
  // раз» только внутри своего изолята).
  if (await _appInForeground()) {
    return (true, 'приложение на экране: работает мгновенный режим');
  }

  final server = prefs.getString(BackgroundSync.keyServer) ?? '';
  final login = prefs.getString(BackgroundSync.keyLogin) ?? '';
  // Пустая строка здесь означает то же, что отсутствие ключа: аккаунт неизвестен,
  // и искать токен в хранилище не по чему
  if (server.isEmpty || login.isEmpty) return (true, 'неизвестен аккаунт: ничего не делаю');

  final token = await DeviceTokenStore().read(server, login);
  // Токена нет (вышли из аккаунта, запись стёрта): проход не ошибка, а «нечего делать».
  // Новый токен здесь не заводится намеренно — для этого нужна веб-сессия пользователя
  if (token == null) return (true, 'нет токена устройства: ничего не делаю');
  final api = SyncApi(serverUrl: server, token: token.token);

  MirrorStore? mirrorStore;
  QueueStore? queueStore;
  final startedAt = DateTime.now().millisecondsSinceEpoch;
  try {
    mirrorStore = await MirrorStore.open();
    queueStore = await QueueStore.open();

    // Связки — для зеркала («Файлы»), выбор папок — для очереди («Фото»): это два разных
    // механизма, и в фоне нужны оба
    final links = SyncLinks(prefs);
    final selection = Selection(prefs);
    final native = NativeFs();
    // Один мост на зеркало и очередь: канал к Android общий, и второй экземпляр ничего
    // не добавил бы, только продублировал бы подписку на события файловой системы
    final engine = MirrorEngine(() => api, mirrorStore, links, native: native);
    final report = await engine.pass(
      budgetMs: passBudgetMs,
      isCancelled: cancelled,
      onProgress: _log,
    );

    // Очередь — только если время осталось: она подготовка, а не срочная работа.
    var queueNote = '';
    final elapsed = DateTime.now().millisecondsSinceEpoch - startedAt;
    if (!cancelled() && elapsed < queueDeadlineMs) {
      queueNote = await _refreshQueue(api, prefs, selection, queueStore, native);
    }

    final note = [
      report.text(),
      // Отказ авторизации — не «ошибка одного файла», а «нужен новый токен», и в фоне сделать
      // это нечем: для выпуска нужна веб-сессия человека. Поэтому говорим прямо, иначе в итоге
      // задания остался бы только счётчик ошибок, а причина — нет
      if (report.authFailed) 'токен устройства отозван — нужен вход в приложение',
      queueNote,
    ].where((s) => s.isNotEmpty).join(' · ');
    await _remember(mirrorStore, '$note (${DateTime.now().toIso8601String()})');
    // Ошибка прохода — это `report.error`: по нему служба решает, просить ли систему повторить
    // задание. Неполный проход (`stopped`, кончился бюджет времени) ошибкой не считается —
    // остаток доедет следующим
    return (report.error == null, note);
  } finally {
    // Базы закрываем всегда: задание короткое, а незакрытые соединения остаются в процессе
    // приложения до самого его конца. Чужие соединения (в том числе приложения) это не трогает:
    // у каждого движка свой обработчик плагина.
    await _close(queueStore);
    await _closeMirror(mirrorStore);
  }
}

/// На экране ли приложение — по ответу службы. Если канал недоступен, считается, что нет:
/// пропущенный проход дороже, чем догадка о том, что приложение открыто.
Future<bool> _appInForeground() async {
  try {
    return await BackgroundChannel().appInForeground();
  } catch (_) {
    // Канал недоступен: считаем, что приложения на экране нет — проход важнее догадки.
    return false;
  }
}

/// Обновить очередь файлов к выгрузке. [api] — уже собранный клиент (сессию заводить заново
/// незачем), [prefs], [selection] и [store] — состояние очереди, [native] — мост для чтения
/// телефона.
///
/// Возвращает текст итога для лога и памяти о проходе. Ошибки не пробрасывает: очередь в фоне —
/// дополнительная работа, и падать из-за неё, уже сделав зеркало, нельзя.
Future<String> _refreshQueue(
  SyncApi api,
  SharedPreferences prefs,
  Selection selection,
  QueueStore store,
  NativeFs native,
) async {
  try {
    final refresher = QueueRefresher(
      () => api,
      SyncPrefs(prefs),
      selection,
      store,
      DeviceFiles(native: native),
    );
    final result = await refresher.refresh(onProgress: _log);
    return result.text();
  } catch (e) {
    return 'очередь не обновлена: $e';
  }
}

/// Запомнить итог прохода в базе зеркала ([keyBackgroundReport]) — по нему приложение
/// показывает, что фоновый проход вообще был. Ошибку записи глотает: память о проходе —
/// удобство, а не работа, и ронять из-за неё задание нельзя.
Future<void> _remember(MirrorStore store, String value) async {
  try {
    await store.setMeta(keyBackgroundReport, value);
  } catch (_) {
    // Память о проходе — удобство, а не работа: не из-за неё ронять задание.
  }
}

/// Закрыть базу очереди, если она открылась. `null` — база не открывалась (ошибка была раньше);
/// ошибку закрытия глушим: закрываем в `finally`, а подменять ею исходную ошибку нельзя.
Future<void> _close(QueueStore? store) async {
  try {
    await store?.close();
  } catch (_) {}
}

/// Закрыть базу зеркала, если она открылась. Отдельно от [_close] — типы разные, а поведение
/// то же: закрыть, что открыто, и не выкинуть исключение на выходе из прохода.
Future<void> _closeMirror(MirrorStore? store) async {
  try {
    await store?.close();
  } catch (_) {}
}

/// Журнал фонового прохода: уходит в logcat (`I/flutter`), другого экрана у задания нет.
///
/// Через `debugPrint`, а не записью в файл: проход идёт без интерфейса, и единственный способ
/// посмотреть, что было ночью, — журнал устройства. Текст поэтому человеческий и короткий.
void _log(String message) => debugPrint('cloudly-sync[фон]: $message');
