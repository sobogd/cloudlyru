import 'package:flutter/services.dart';

/// Канал фонового прохода: `ru.cloudly.sync/background` (см. `BackgroundBridge.kt`).
///
/// Одним каналом пользуются обе стороны. Приложение заводит и снимает задание; фоновый изолят
/// спрашивает, не на экране ли приложение, сообщает об итоге и принимает просьбу остановиться,
/// когда система отбирает задание.
///
/// Отдельный канал, а не общий `ru.cloudly.sync/native`: тот отвечает за системные вызовы
/// (доступ к файлам, номера файлов, наблюдение), а здесь — только жизнь фонового задания.
///
/// ## Контракт с нативным Kotlin
///
/// Обработчик — `BackgroundBridge.kt`. Вызовы Dart → Kotlin:
///
/// | метод | аргументы | ответ Kotlin | что значит «ложь»/пусто |
/// |---|---|---|---|
/// | `appInForeground` | нет | `Boolean` — есть ли started-активности (`AppPresence`) | `false` — приложение не на экране (или процесс поднят самим заданием, тогда активностей нет вовсе) |
/// | `stopRequested` | нет | `Boolean` — флаг службы задания или моста | `false` — остановку не просили |
/// | `budgets` | нет | `Map` с ключами `pass`, `queue` (мс) | ответ не картой или без нужных ключей — «бюджет неизвестен», берутся запасные значения (`background_pass.dart`) |
/// | `finished` | `{ok: Boolean, note: String?}` | `true` (значение Dart не использует) | — |
/// | `ensureJob` | нет | `Boolean` — `SyncJobScheduler.isScheduled()` после постановки | `false` — задание не заведено (система отказала) |
/// | `cancelJob` | нет | `Boolean` — `!SyncJobScheduler.isScheduled()` | `false` — задание снять не удалось |
///
/// `note` может быть `null`: Kotlin читает его как nullable и пишет в лог, только если он есть.
/// Неизвестный метод Kotlin отвечает `notImplemented()`, и Dart получает `MissingPluginException`.
///
/// Вызов Kotlin → Dart один: `cancel` с пустыми аргументами (`requestStop()`). Его принимает
/// слушатель, поставленный только фоновым изолятом (см. конструктор); ответ Kotlin не читает —
/// вызов обёрнут в `runCatching`, чтобы не заваливать службу, если изолята уже нет.
///
/// Канал ставится дважды — на движке приложения (`MainActivity`) и на движке задания
/// (`SyncJobService`): у каждого движка свой мессенджер, и общий экземпляр тут невозможен.
/// Ответ про «на экране» от экземпляра не зависит — `AppPresence` живёт на процесс целиком.
/// А флаг остановки — наоборот, свойство задания: его хранит служба (`SyncJobService`), и мост
/// задания читает его оттуда, поэтому просьба не теряется, если система остановила задание
/// раньше, чем движок и мост успели появиться.
class BackgroundChannel {
  /// [listenCancel] — ставить ли слушателя просьбы «остановись».
  BackgroundChannel({bool listenCancel = false}) {
    // Слушателя ставит только фоновый изолят: приложению просьба «остановись» не адресована.
    if (listenCancel) _channel.setMethodCallHandler(_handle);
  }

  static const MethodChannel _channel = MethodChannel('ru.cloudly.sync/background');

  /// Система отобрала задание: проход должен закончиться на ближайшей проверке, а не на
  /// середине выгрузки. Движок уже такой: `isCancelled` он спрашивает между файлами.
  ///
  /// Ставится из [runBackgroundPass]; `null` (никто не подписан) — просьба просто теряется,
  /// поэтому у Kotlin есть ещё и флаг, который изолят спрашивает сам через [stopRequested].
  void Function()? onCancel;

  /// Приём просьбы об остановке. Отвечать нечем и не нужно: Kotlin ответ не читает, а ошибку
  /// доставки гасит у себя. Любой другой метод игнорируется — канал общий, и падать на
  /// неожиданном вызове изоляту незачем.
  Future<void> _handle(MethodCall call) async {
    if (call.method == 'cancel') onCancel?.call();
  }

  /// Приложение на экране? Тогда проход делает мгновенный режим: он замечает изменения за
  /// секунды, а проход из фона только спорил бы с ним за базы (см. `background_pass.dart`).
  ///
  /// Ответ читается как «нет», если канал молчит или метода нет: молчание канала — не довод
  /// считать, что приложение открыто.
  Future<bool> appInForeground() async =>
      await _channel.invokeMethod<bool>('appInForeground') ?? false;

  /// Остановку просили ещё до того, как изолят поставил слушателя: тогда событие потерялось бы,
  /// поэтому у той стороны есть и флаг, который можно спросить.
  ///
  /// Вызывается один раз в начале прохода. Ответ «нет» при недоступном канале — нормальное
  /// поведение: проход важнее догадки.
  Future<bool> stopRequested() async =>
      await _channel.invokeMethod<bool>('stopRequested') ?? false;

  /// Сколько времени отведено работе за одно задание: бюджет зеркала и дедлайн наполнения
  /// очереди (мс, оба считаются от начала прохода).
  ///
  /// Числа живут на нативной стороне (`SyncJobService.JOB_TIMEOUT_MS` → `PASS_BUDGET_MS`
  /// и `QUEUE_DEADLINE_MS`): там же предохранитель задания и знание таймаута системы, поэтому
  /// копия в Dart разъезжалась бы с ними при первой правке. Здесь `null` — «канал молчит»
  /// (движок поднят без моста, старая сборка): тогда вызывающий берёт запасные значения
  /// из `background_pass.dart`, потому что проход важнее точности бюджета.
  Future<({int pass, int queue})?> budgets() async {
    try {
      final raw = await _channel.invokeMethod<Map<dynamic, dynamic>>('budgets');
      final pass = raw?['pass'];
      final queue = raw?['queue'];
      if (pass is! int || queue is! int || pass <= 0 || queue <= 0) return null;
      return (pass: pass, queue: queue);
    } catch (_) {
      return null;
    }
  }

  /// Работа кончена: служба может закрыть движок и доложить системе об итоге.
  ///
  /// [ok] — проход закончился без ошибки (`false` — система повторит задание), [note] —
  /// человеческий итог для лога logcat, может быть `null`.
  ///
  /// Ничего не возвращает. Если движок приложения уже закрыт, вызов бросает
  /// `MissingPluginException` — [runBackgroundPass] его перехватывает: отвечать тогда некому.
  Future<void> finished({required bool ok, String? note}) =>
      _channel.invokeMethod<void>('finished', {'ok': ok, 'note': note});

  /// Завести периодическое задание: вызывается приложением при входе в аккаунт.
  ///
  /// Возвращает `true`, только если задание в системе действительно есть. `false` — система
  /// отказала (лимит заданий, запрет на persisted) или канал недоступен; вызывающий
  /// (`BackgroundSync.register`) на это не реагирует: останется мгновенный режим в приложении.
  Future<bool> ensureJob() async =>
      await _channel.invokeMethod<bool>('ensureJob') ?? false;

  /// Снять задание: при выходе из аккаунта. Без токена оно всё равно ничего не делает,
  /// но пусть не будит приложение зря.
  ///
  /// Возвращает `true`, если заданий с этим номером в системе не осталось. `false` — канал
  /// недоступен или задание всё ещё заведено; ошибкой для вызывающего это не считается.
  Future<bool> cancelJob() async =>
      await _channel.invokeMethod<bool>('cancelJob') ?? false;
}
