/// Device-токен: им синхронизатор ходит в облако.
///
/// Заводится на устройство, а не на человека: по токену сервер привязывает корень зеркала
/// (`<Имя устройства> - Файлы`), поэтому у каждого телефона своя папка. Пользуются им
/// [SyncApi] (каждый запрос синхронизации), [DeviceTokenStore] (хранение между запусками) и
/// фоновый изолят (`background_pass.dart`), который достаёт токен из хранилища сам, без
/// участия приложения.
class DeviceToken {
  /// [token] — секрет, он уходит в заголовок `Authorization: Bearer`; [id] и [label] отдаёт
  /// сервер, и нужны они только чтобы показать токен человеку в настройках.
  const DeviceToken({required this.token, this.id, this.label = ''});

  /// Секрет. Пустым не бывает: [ensureDeviceToken] на пустой ответ сервера бросает [StateError],
  /// а не сохраняет запись, которой нельзя пользоваться.
  final String token;

  /// id токена на сервере. null — сервер его не отдал (у записей из прежних сборок).
  final String? id;

  /// Имя токена, как его показывает сервер (обычно «модель устройства»). Может быть пустым:
  /// тогда для показа берётся имя, переданное при заведении токена.
  final String label;
}

/// Хранилище device-токена. Токен даёт полный доступ к облаку, а телефон — потеряемая вещь,
/// поэтому лежит он в шифрованном хранилище системы, а не в обычных настройках.
///
/// Ключ включает адрес сервера и логин: корень зеркала сервер заводит **устройству**, то есть
/// токену, и подмена токена на чужой означала бы выгрузку в папку другого аккаунта.
class DeviceTokenStore {
  /// [storage] — где лежит токен; по умолчанию системное шифрованное хранилище. Параметр
  /// нужен, чтобы подставить своё хранилище, не заводя второй такой же класс.
  DeviceTokenStore({FlutterSecureStorage? storage})
      : _storage = storage ?? _systemStorage();

  final FlutterSecureStorage _storage;

  /// Шифрованное хранилище системы: связка ключей на Apple, хранилище платформы на Android.
  ///
  /// На macOS берётся **классическая** связка, а не «data protection»
  /// (`usesDataProtectionKeychain: false`), и это не мелочь: data protection доступна только
  /// приложению с настоящей подписью и правом `keychain-access-groups`, а наша сборка подписана
  /// ad-hoc — сертификата Developer ID у неё нет. Проверено на этом маке:
  ///
  ///  * без права `SecItemAdd` с флагом `kSecUseDataProtectionKeychain` отвечает `-34018`
  ///    («A required entitlement isn't present»), а без флага — `0`, то есть успех;
  ///  * если право всё-таки вписать в ad-hoc подпись, система убивает процесс при запуске
  ///    (проверено: `Killed: 9`) — этот путь не «правильнее», а нерабочий вовсе.
  ///
  /// Отсюда и бралась ошибка «токен устройства не выпущен»: обращение к хранилищу падало
  /// раньше, чем дело доходило до сервера. Классическая связка работает без прав, но помнит,
  /// какая сборка завела запись: после обновления приложения система может один раз спросить
  /// разрешение на доступ к своей же записи (кнопка «Always Allow» — и больше не спросит).
  static FlutterSecureStorage _systemStorage() => const FlutterSecureStorage(
        mOptions: MacOsOptions(usesDataProtectionKeychain: false),
      );

  /// Прочитать токен для пары «адрес сервера + логин».
  ///
  /// Возвращает `null`, если записи нет, она пуста, в ней нет поля `token` или JSON не
  /// разбирается: испорченная запись для вызывающих неотличима от отсутствия, и это правильно —
  /// иначе разбирать мусор пришлось бы тому, кто просто хочет завести новый токен.
  ///
  /// Разбор JSON обёрнут в try, а само обращение к хранилищу — нет: сбой шифрованного
  /// хранилища (например, отозван ключ шифрования) наружу проходит исключением, и решение,
  /// что делать, остаётся за вызывающим.
  Future<DeviceToken?> read(String serverUrl, String login) async {
    final raw = await _storage.read(key: _key(serverUrl, login));
    if (raw == null || raw.isEmpty) return null;
    try {
      final j = json.decode(raw) as Map<String, dynamic>;
      final token = '${j['token'] ?? ''}';
      if (token.isEmpty) return null;
      return DeviceToken(
        token: token,
        // id из старой записи мог быть положен числом: приводим к строке, а не приводим тип
        id: j['id'] == null ? null : '${j['id']}',
        label: '${j['label'] ?? ''}',
      );
    } catch (_) {
      return null;
    }
  }

  /// Положить токен в хранилище. Исключений не глотает: если запись не удалась, вызывающий
  /// ([ensureDeviceToken]) должен узнать об этом сейчас, а не выяснять потом, почему зеркало
  /// ходит в облако без токена.
  Future<void> write(String serverUrl, String login, DeviceToken token) => _storage.write(
        key: _key(serverUrl, login),
        value: json.encode({'token': token.token, 'id': token.id, 'label': token.label}),
      );

  /// Забыть токен: **обязательный** шаг выхода из аккаунта и смены логина.
  ///
  /// Удаление отсутствующего ключа для хранилища не ошибка, поэтому вызывать можно сколько
  /// угодно раз. Забыть запись обязательно: иначе локальная копия токена переживает «выход»,
  /// хотя интерфейс считается разлогиненным, и следующая привязка молча вернёт прежний токен
  /// вместе с его корнем зеркала. Сам серверный токен этим не отзывается — его гасит
  /// `SyncApi.revokeOwnToken`, а при перевыпуске — [ensureDeviceToken] (см. ниже).
  Future<void> clear(String serverUrl, String login) =>
      _storage.delete(key: _key(serverUrl, login));

  /// Ключ записи: сервер и логин вместе. На одном сервере может быть несколько аккаунтов, и
  /// общий ключ подсунул бы второму аккаунту токен первого — то есть выгрузку в чужую папку.
  String _key(String serverUrl, String login) => 'device_token|$serverUrl|$login';
}

/// Токен устройства для синхронизации: свой у каждого устройства, чтобы корень зеркала в
/// облаке не делился между телефонами (иначе удаление на одном уносило бы файлы другого).
///
/// Хранимый токен переиспользуется: новый токен — это новый корень зеркала, и после каждого
/// входа-выхода облако получало бы ещё одну папку с тем же содержимым. Новый заводится,
/// только если прежний отозван или его нет.
///
/// [session] — веб-сессия пользователя: только она умеет выпускать токены; [store] — где искать
/// и куда положить готовый токен; [serverUrl] и [login] — ключ в хранилище и адрес проверки;
/// [label] — имя, под которым токен (и корень зеркала) будет видно в облаке.
///
/// Возвращает живой токен: сохранённый, если сервер на него отвечает, иначе свежевыпущенный
/// (он сразу записывается в [store]). Побочные эффекты — запрос к серверу, отзыв прежнего
/// токена, если он оказался мёртвым, и запись в шифрованное хранилище.
///
/// Прежний токен отзывается ([_revokeOld]) до выпуска нового: оставлять его живым нельзя —
/// он даёт полный доступ к облаку до истечения срока, а новый токен заводит в облаке второй
/// корень зеркала (`<Устройство> - Файлы`), то есть вторую папку с тем же содержимым.
/// Неудача отзыва выпуск нового токена не отменяет (без токена синхронизация не работает
/// вовсе) и уходит строкой в лог: показать её в интерфейсе — дело вызывающего, у которого
/// есть `tokenError` и экран настроек.
///
/// Бросает [StateError], если сервер ответил успехом, но поля `token` в ответе нет: работать
/// с пустым токеном нельзя, а молча вернуть его значило бы сломать синхронизацию позже и
/// в другом месте. Сбой проверки сохранённого токена наружу не выходит — он означает лишь,
/// что живость проверить не удалось (см. [_isAlive]), и тогда берётся сохранённый токен.
/// А вот сбой самого выпуска нового токена (нет сети, отказ сервера) уходит исключением:
/// вызывающему нужно знать, что токена нет, а не получить пустышку.
Future<DeviceToken> ensureDeviceToken({
  required CloudlyApi session,
  required DeviceTokenStore store,
  required String serverUrl,
  required String login,
  required String label,
}) async {
  final saved = await store.read(serverUrl, login);
  if (saved != null) {
    final alive = await _isAlive(saved.token, serverUrl);
    if (alive) return saved;
    // Токен мёртв — тем важнее убрать его с сервера: «мёртвым» он может быть только для нас
    // (истёк срок, сервер ответил 403 на часть ручек). Живой лишний токен — это оставленный
    // доступ к облаку, о котором человек не знает
    await _revokeOld(session, saved);
  }
  final created = await session.createToken(label);
  final token = DeviceToken(
    token: '${created['token'] ?? ''}',
    id: created['id'] == null ? null : '${created['id']}',
    label: '${created['label'] ?? label}',
  );
  if (token.token.isEmpty) throw StateError('сервер не выдал токен устройства');
  await store.write(serverUrl, login, token);
  return token;
}

/// Отозвать прежний токен по сохранённому id, прежде чем выпускать новый.
///
/// Серверная ручка `DELETE /auth/tokens/:id` доступна только веб-сессии — она здесь и есть
/// ([CloudlyApi]). Исключений не бросает: без нового токена синхронизация не работает вовсе,
/// а живой «лишний» токен — это доступ, который человек уберёт руками в «Настройках» →
/// «Токены приложений». Причина отказа попадает в лог (`debugPrint`), а не теряется: иначе
/// на телефоне не осталось бы ни следа.
Future<void> _revokeOld(CloudlyApi session, DeviceToken saved) async {
  final id = saved.id;
  if (id == null || id.isEmpty) {
    debugPrint(
      'cloudly-sync: прежний токен устройства отозвать нечем — сервер не отдал его id',
    );
    return;
  }
  try {
    await session.revokeToken(id);
    debugPrint('cloudly-sync: прежний токен устройства отозван ($id)');
  } catch (e) {
    debugPrint('cloudly-sync: прежний токен устройства не отозван ($id): $e');
  }
}

/// Живой ли токен: сервер отвечает отказом на отозванный, и тогда нужен новый.
///
/// [token] проверяется запросом `GET /auth/me` на [serverUrl]. Возвращает `true` и на удачный
/// ответ, и на любую ошибку, кроме 401/403: молчащая сеть или пятисотая сервера ни о чём не
/// говорят, а выбросить рабочий токен из-за них дороже — новый токен это новая папка в облаке.
/// Исключений не бросает: ответ «жив» безопаснее отказа.
Future<bool> _isAlive(String token, String serverUrl) async {
  try {
    await SyncApi(serverUrl: serverUrl, token: token).meInfo();
    return true;
  } catch (e) {
    // 401/403 — токен мёртв; сеть может просто молчать, и тогда токен не виноват
    if (e is SyncApiException) return e.status != 401 && e.status != 403;
    return true;
  }
}
