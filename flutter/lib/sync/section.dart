/// Разделы синхронизации. Раньше их было два — «Файлы» и «Фото»; «Фото» (автоматическая
/// выгрузка фото и видео в медиатеку) убрано, остался один раздел.
///
/// Раздел — это ещё и ключ: [storageKey] лежит в базе и настройках, и по нему синхронизатор
/// понимает, к какому разделу относится строка. Значения создаёт код разделов и интерфейс,
/// синхронизация их только читает.
enum Section {
  files('FILES', 'Файлы');

  /// Ключ и подпись задаются здесь же: раздел — это перечисление, а не запись в базе.
  const Section(this.storageKey, this.label);

  /// Как раздел записан в базе и настройках: значения менять нельзя — там уже лежат данные.
  final String storageKey;

  /// Подпись для интерфейса. В базе не хранится, поэтому её можно менять свободно.
  final String label;

  /// Раздел по значению из базы: неизвестное значение — не повод падать.
  ///
  /// Возвращает `null`, если ключа нет среди [Section.values]: например, строка из базы
  /// прежней сборки, где ещё был раздел «Фото». Ни базы, ни файлов не трогает.
  static Section? byStorageKey(String? key) {
    for (final s in Section.values) {
      if (s.storageKey == key) return s;
    }
    return null;
  }
}
