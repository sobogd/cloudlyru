import 'dart:async';

import 'package:flutter/foundation.dart';

import '../data/mirror_store.dart';
import '../device/native_fs.dart';
import 'mirror_engine.dart';
import 'mirror_status.dart';
import 'mirror_watcher.dart';

/// Мгновенная реакция, пока приложение работает.
///
/// Два канала:
///   • облако → телефон: частый опрос головы журнала (`GET /sync/head` — крошечный запрос).
///     Голова сдвинулась — сразу догоняем журнал, файлы приезжают за секунды;
///   • телефон → облако: событие файловой системы ([MirrorWatcher]) запускает проход почти
///     сразу, с короткой выдержкой на всплеск событий.
///
/// Пока приложение выгружено из памяти, наблюдать некому — тогда работает только страховочный
/// периодический проход, который будит система (`SyncJobScheduler.kt`): 15 минут там не период,
/// а минимум, и в Doze задание может прийти заметно позже. Резидентного сервиса с постоянным
/// уведомлением по умолчанию нет: это цена, которую пользователь не выбирал.
///
/// Тик без токена ничего не делает, а тик со сбоем не останавливает опрос, а откладывает его:
/// в Doze сеть всё равно спит, и долбить её каждые три секунды смысла нет, но и бросать опрос
/// нельзя — иначе после сна сети синхронизация не вернулась бы сама.
///
/// Создаётся [SyncController] после старта синхронизации, живёт в области приложения.
class MirrorLive {
  /// Зависимости приходят готовыми: склад, движок, состояние, наблюдатель и доступ к файлам
  /// заводит и держит [SyncController]. Два обработчика — [hasToken] и [foreground] —
  /// назначаются сразу после создания: без них цикл опроса считает, что токена нет.
  MirrorLive(
    this._store,
    this._engine,
    this._status,
    this._watcher,
    this._native,
  );

  final MirrorStore _store;
  final MirrorEngine _engine;
  final MirrorStatusHolder _status;
  final MirrorWatcher _watcher;
  final NativeFs _native;

  /// Как часто спрашивать голову журнала. Запрос крошечный (одна строка по индексу),
  /// лимит сервера на эту ручку — 240 в минуту, так что 40 в минуту не мешают.
  ///
  /// Полторы секунды, а не три: правка из веба должна появляться на телефоне «сразу», и
  /// задержка опроса — единственное, что стоит между ними. Сеть при этом не страдает: запрос
  /// без тела, а догон запускается только когда голова правда сдвинулась.
  static const int pollMs = 1500;

  /// В фоне: экран погашен, мгновенность не нужна, а батарея нужна.
  static const int pollBackgroundMs = 30000;

  /// Сервер молчит или сети нет: ждём дольше, но не бросаем опрос совсем.
  static const int failBackoffMs = 60000;

  Timer? _timer;

  /// Идёт ли цикл опроса. Снимается только [stop]: сбой на одном тике его не прекращает.
  bool _running = false;

  /// Сбои подряд: пока их нет, впереди опрашиваем быстро, после сбоя — редко.
  int _failures = 0;

  /// Есть ли токен: без него опрашивать нечего и незачем.
  bool Function() hasToken = () => false;

  /// Приложение на экране: тогда спрашиваем журнал часто, в фоне — редко.
  bool Function() foreground = () => true;


  /// Запустить цикл опроса. Повторный вызов ничего не делает.
  ///
  /// Первый тик — через [pollMs]: опрашивать облако в тот же момент, когда приложение
  /// открылось и всё равно делает полный проход, незачем.
  void start() {
    if (_running) return;
    _running = true;
    _schedule(pollMs);
  }

  /// Остановить опрос: таймер снимается, счётчик сбоев обнуляется. Хранилище и наблюдение за
  /// папками не трогаются — этим занимается [dispose].
  void stop() {
    _running = false;
    _timer?.cancel();
    _timer = null;
    _failures = 0;
  }

  /// Поставить следующий тик: один таймер за раз, иначе после ошибки тики копились бы.
  ///
  /// После [stop] новый таймер не заводится: тик может дойти до этой точки уже после остановки
  /// (он асинхронный), и без проверки опрос продолжался бы после выхода из аккаунта.
  void _schedule(int ms) {
    if (!_running) return;
    _timer?.cancel();
    _timer = Timer(Duration(milliseconds: ms), _tick);
  }

  /// Один тик: догон журнала, если голова сдвинулась.
  ///
  /// Побочные эффекты: запросы к серверу, возможно полный/журнальный догон (он же пишет в базу
  /// и в файловую систему) и обновление статуса. Исключения наружу не выходят: любой сбой —
  /// это лишь более длинная пауза до следующего тика.
  Future<void> _tick() async {
    if (!_running) return;
    var next = foreground() ? pollMs : pollBackgroundMs;
    try {
      // токена нет — спрашивать нечего: тик выходит тихо, но цикл продолжается, чтобы
      // после выпуска токена опрос возобновился сам
      if (!hasToken()) {
        _schedule(next);
        return;
      }

      // файл, отложенный окном стабильности, ждёт своей минуты: возвращаемся к нему.
      // Проход идёт без колбэка прогресса — в интерфейсе он не отображается
      // Отложенный проход (файл ещё писался) — только на переднем плане: в фоне тем же
      // занимается задание системы, а два движка на одной базе спорят за одни строки
      final retry = MirrorRetryClock(_engine);
      if (foreground() && await retry.runIfDue(_store)) {
        if (!_running) return;
        _failures = 0;
        _schedule(next);
        return;
      }
      if (!_running) return;

      // курсора нет — зеркало ещё не сделало первый проход, догонять нечего
      final cursor = await _store.cursor();
      if (cursor == null) {
        _schedule(next);
        return;
      }

      final head = await _engine.syncHead();
      if (!_running) return;
      _failures = 0;
      // связь есть: даже если догонять нечего, «спрашивали облако» — полезная отметка,
      // а прошлая ошибка связи больше не актуальна
      _status.update((s) => s.copyWith(clearError: true));
      if (head > cursor) {
        // Догон журнала — облачная сторона, диска не касается: его можно делать и в фоне.
        // Но сбой движок отдаёт значением, а не исключением, поэтому смотрим на отчёт:
        // без этого отказ /sync/changes превращался бы в опрос догона каждые три секунды
        final report = await _engine.catchUpCloud();
        if (report.error != null || report.stopped) {
          _failures += 1;
          next = failBackoffMs;
        }
      }
    } catch (_) {
      // причину не запоминаем: следующий удачный тик её снимет, а показывать в интерфейсе
      // «облако недоступно» при живом проходе в очереди было бы громче правды
      _failures += 1;
      next = failBackoffMs;
    }
    if (_failures == 0 && foreground()) next = pollMs;
    _schedule(next);
  }

  /// Наблюдение за папками и проход по событию файловой системы.
  ///
  /// Подписывается на [MirrorWatcher.onPass] — единственного потребителя событий файловой
  /// системы; вызывается один раз при создании.
  void bindWatcher() {
    _watcher.onPass = () async {
      // без токена проход всё равно ничего не сделает, а работу на диск потратит
      if (!hasToken()) return false;
      // Проход по событию файловой системы делается только на переднем плане: в фоне
      // сверку ведёт задание системы, и два прохода по одной базе (каждый со своим движком)
      // спорили бы за одни строки, дважды выгружали один файл и гоняли предохранители.
      // Догон журнала в фоне при этом остаётся — он висит на опросе головы выше
      if (!foreground()) return false;
      // Падение внутри прохода стало бы необработанной ошибкой всего приложения — а сверка
      // обязана ошибаться тихо, поэтому исключение превращаем в отчёт
      final report = await _engine.pass().catchError((Object e) {
        debugPrint('cloudly-sync: проход по событию упал: $e');
        return MirrorReport()..error = '$e';
      });
      // finishedAt == 0 — проход не начинался: его отбил замок «один проход за раз»
      return report.finishedAt > 0;
    };
  }

  /// Остановить опрос, снять наблюдение за папками и отпустить его у [NativeFs].
  ///
  /// Отказ любого из шагов не мешает остальным: `stop` — синхронный, а снятие наблюдения
  /// и `unwatch` идут по очереди.
  Future<void> dispose() async {
    stop();
    await _watcher.stop();
    await _native.unwatch();
  }
}
