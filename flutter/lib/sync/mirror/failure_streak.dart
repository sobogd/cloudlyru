import '../net/sync_api.dart';

/// Счётчик подряд идущих сбоев одной и той же работы.
///
/// Сеть может отвалиться посреди прохода. Тогда каждый следующий файл ждёт таймаута (до
/// двадцати секунд на соединение), а проход молотит впустую весь свой бюджет: на телефоне это
/// минуты ожидания и разряженная батарея, а человек видит «проход не закончен» без причины.
/// После нескольких сбоев подряд проход останавливается: остальное доедет следующим — его
/// назначит догон, — а в отчёте будет написано, что именно не вышло.
///
/// Отказ авторизации (401/403) считается смертельным сразу: с отозванным токеном повторять
/// бессмысленно, сколько бы файлов ни осталось.
///
/// Одиночные сбои — нормальная жизнь сети, поэтому успешная операция обнуляет счётчик.
class FailureStreak {
  FailureStreak({this.limit = 5});

  /// Сколько сбоев подряд считаем «сеть легла».
  final int limit;

  int _count = 0;
  bool _fatal = false;
  String? _reason;

  /// Успешная операция: счётчик сбрасывается, причина забывается.
  void success() {
    _count = 0;
    _fatal = false;
    _reason = null;
  }

  /// Записать сбой. Возвращает true, если после него работу пора прекращать.
  bool failure(Object error) {
    _count += 1;
    _fatal = _fatal || _isFatal(error);
    // Причину держим первую: она ближе всего к тому, что на самом деле сломалось
    _reason ??= _describe(error);
    return broken;
  }

  /// Пора прекращать: либо счётчик выбрал предел, либо отказ необратимый.
  bool get broken => _fatal || _count >= limit;

  /// Почему остановились — для отчёта о проходе.
  String? get reason => broken ? _reason : null;

  static bool _isFatal(Object error) =>
      error is SyncApiException && (error.status == 401 || error.status == 403);

  static String _describe(Object error) {
    if (_isFatal(error)) return 'токен отозван — войдите заново';
    return '$error';
  }
}
