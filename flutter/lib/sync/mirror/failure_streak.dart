import 'dart:io';

import '../net/sync_api.dart';

/// Счётчик подряд идущих сбоев одной и той же работы.
///
/// Сеть может отвалиться посреди прохода. Тогда каждый следующий файл ждёт таймаута (до
/// двадцати секунд на соединение), а проход молотит впустую весь свой бюджет: на телефоне это
/// минуты ожидания и разряженная батарея, а человек видит «проход не закончен» без причины.
/// После нескольких сбоев подряд проход останавливается: остальное доедет следующим — его
/// назначит догон, — а в отчёте будет написано, что именно не вышло.
///
/// Отказ авторизации (401/403) считается смертельным сразу: с отозванным токеном повторять
/// бессмысленно, сколько бы файлов ни осталось.
///
/// Одиночные сбои — нормальная жизнь сети, поэтому успешная операция обнуляет счётчик.
///
/// Живёт ровно один проход и одну серию работы: `MirrorPull` заводит свой счётчик на
/// скачивание, `MirrorEngine._pushLocal` — один на переименования, выгрузку и удаления
/// (подряд идущими считаются операции всей серии, а не каждой петли в отдельности).
class FailureStreak {
  /// @param limit сколько сбоев подряд считаем «сеть легла». Пяти хватает, чтобы отличить
  ///        серию от одиночных ошибок, и мало настолько, чтобы не ждать таймаутов десятками.
  FailureStreak({this.limit = 5});

  /// Сколько сбоев подряд считаем «сеть легла».
  final int limit;

  int _count = 0;
  bool _fatal = false;
  String? _reason;

  /// Успешная операция: счётчик сбрасывается, причина забывается.
  ///
  /// Смертельный отказ тоже снимается: раз операция прошла, держать на нём остановку больше
  /// не за что. Побочных эффектов нет.
  void success() {
    _count = 0;
    _fatal = false;
    _reason = null;
  }

  /// Записать сбой. Возвращает true, если после него работу пора прекращать.
  ///
  /// Ошибка файловой системы в счётчик не идёт вовсе: она про один файл или папку (имя
  /// не подошло тому, кончилось место, каталог занят), а счётчик отвечает на вопрос «легло ли
  /// соединение». Пять таких подряд раньше останавливали весь проход с диагнозом «облако
  /// недоступно», хотя облако было в порядке; считается такая ошибка вызывающим — в [MirrorReport.failed].
  ///
  /// Состояние счётчика — единственное, что меняется: ни базы, ни сети, ни файлов. Решение
  /// по возвращённому значению принимает вызывающий (остановка прохода и текст в отчёт).
  bool failure(Object error) {
    if (error is FileSystemException) return broken;
    _count += 1;
    // смертельный отказ не снимается до ближайшей успешной операции: серия с 401 так и
    // остаётся смертельной, даже если часть файлов позже прошла
    final fatal = _isFatal(error);
    _fatal = _fatal || fatal;
    if (fatal) {
      // Причина смертельного отказа перетирает прежнюю: по ней принимается решение
      // (перевыпустить токен), и «мигнула сеть, потом 401» не должен её прятать
      _reason = _describe(error);
    } else if (!_fatal) {
      // Причину держим первую — ту, с которой серия началась: дальше обычно идёт одна и та же
      // ошибка, а первая ближе к моменту, когда всё сломалось
      _reason ??= _describe(error);
    }
    return broken;
  }

  /// Пора прекращать: либо счётчик выбрал предел, либо отказ необратимый.
  bool get broken => _fatal || _count >= limit;

  /// Остановились из-за отказа авторизации (401/403): нужен новый токен, а не повтор.
  ///
  /// Признак структурный, а не по тексту ошибки: строку «токен отозван» формирует сам клиент,
  /// и распознавать по ней причину — значит зависеть от формулировки.
  bool get authFailed => _fatal;

  /// Почему остановились — для отчёта о проходе.
  ///
  /// Пока останавливаться не за чем, молчит: причина без остановки — шум в отчёте.
  String? get reason => broken ? _reason : null;

  /// Отказ авторизации: токен отозван или не подходит. Повторять бессмысленно — нужен новый.
  static bool _isFatal(Object error) =>
      error is SyncApiException && (error.status == 401 || error.status == 403);

  /// Ошибка словами для отчёта: у смертельного отказа текст свой, у остальных — `toString`.
  static String _describe(Object error) {
    if (_isFatal(error)) return 'токен отозван — войдите заново';
    return '$error';
  }
}
