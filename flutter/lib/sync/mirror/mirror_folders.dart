import 'dart:io';

import '../data/mirror_store.dart';
import '../net/sync_api.dart';

/// Папки зеркала: соответствие путей на телефоне и папок в облаке.
///
/// Самой связанной папки это не касается: папку в облаке выбрал человек, и её id уже лежит
/// в паре ([MirrorStore.putRoot]). Здесь заводятся только вложенные папки: путь внутри папки
/// связки повторяется в облаке (`Download/Telegram` → `<папка связки>/Telegram`) идемпотентным
/// `ensure-path`, поэтому проход можно повторять сколько угодно раз.
///
/// Имя пути приходит от вызывающего (`relDir`), а не выводится здесь: `ensure-path` на сервере
/// — это find-or-create **по имени** внутри родителя.
///
/// Соответствие кэшируется и в памяти, и в базе: правка из журнала знает только `folderId`,
/// и без обратного перевода её некуда положить на телефоне.
///
/// Создаётся движком на каждый проход (`MirrorEngine._passLocked`), поэтому кэш в памяти живёт
/// один проход: на следующем пары берутся из базы и из `ensure-path`.
class MirrorFolders {
  MirrorFolders(this._api, this._store);

  final SyncApi _api;
  final MirrorStore _store;

  /// Ключ — путь на телефоне: один и тот же путь в разных связках — разные записи,
  /// и кэш не должен схлопывать их в одну.
  final Map<String, String> _byLocalPath = {};

  /// Папка для относительного пути (`Telegram` внутри связки на `Download`).
  ///
  /// @param relDir путь внутри связанной папки без её имени — ровно то, что уходит на сервер;
  ///        @param localPath тот же путь на телефоне (ключ кэша), @param parentCloudId id папки
  ///        облака той связки, внутри которой лежит путь.
  /// @return идентификатор папки облака. Побочные эффекты: запрос `ensure-path` (сеть) и запись
  ///         пары в базу. При ошибке сети или сервера исключение уходит наверх — вызывающий
  ///         считает это неудачей выгрузки, а строка в базе остаётся от прошлого раза.
  Future<String> ensure(
    String relDir,
    String localPath,
    String parentCloudId,
  ) async {
    final cached = _byLocalPath[localPath];
    if (cached != null) {
      // пару всё равно переписываем: соседний проход (или фоновое задание) мог её снести
      await _store.registerDir(cached, localPath);
      return cached;
    }
    final id = await _ensurePath(relDir, parentCloudId);
    _byLocalPath[localPath] = id;
    await _store.registerDir(id, localPath);
    return id;
  }

  /// Сколько раз пробуем завести папку, если сервер ограничивает частоту (429).
  static const int _ensureAttempts = 4;

  /// Первая пауза между попытками. Дальше она удваивается: 2, 4 и 8 секунд.
  static const int _ensureFirstWaitMs = 2000;

  /// Сервер ограничивает частоту (429). Первый проход по дереву заводит десятки папок, и
  /// упереться в лимит на середине — значит уронить проход на ровном месте.
  ///
  /// [_ensureAttempts] попытки с паузами [_ensureFirstWaitMs], вдвое и вчетверо: дольше ждать
  /// незачем — проход ограничен бюджетом времени, а остальные папки заведёт следующий. Суммарно
  /// это до 14 секунд ожидания внутри прохода: их видно в прогрессе только как паузу между
  /// строками, отдельного сообщения у них нет. Иные ошибки (в том числе 401) не повторяем:
  /// они не пройдут сами, и исключение уходит вызывающему.
  Future<String> _ensurePath(String path, String parentId) async {
    var waitMs = _ensureFirstWaitMs;
    for (var attempt = 0; attempt < _ensureAttempts; attempt++) {
      try {
        return await _api.ensurePath(path, parentId);
      } on SyncApiException catch (e) {
        // последняя попытка ретранслирует исключение: сюда доходит только она, поэтому
        // «не принял и после всех попыток» — это и есть её ошибка, отдельная ветка не нужна
        if (e.status != 429 || attempt == _ensureAttempts - 1) rethrow;
        await Future<void>.delayed(Duration(milliseconds: waitMs));
        waitMs *= 2;
      }
    }
    // Недостижимо: цикл либо возвращает папку, либо ретранслирует исключение на последней
    // попытке. Оставлено, чтобы компилятор видел возврат значения на всех путях
    throw StateError('папку $path сервер так и не принял');
  }
}

/// Папка на телефоне: создать, если её нет. Пустая структура тоже должна доехать до облака,
/// поэтому папки заводятся отдельно от файлов.
///
/// @param path полный путь на телефоне (включая все родительские — создаются рекурсивно).
/// Существующую папку не трогает: содержимое не переписывается и не проверяется. При отказе
/// файловой системы (нет прав, кончилось место) исключение уходит наверх — вызывающий решает,
/// считать ли это неудачей.
Future<void> ensureLocalDir(String path) async {
  final dir = Directory(path);
  if (!await dir.exists()) {
    await dir.create(recursive: true);
  }
}
