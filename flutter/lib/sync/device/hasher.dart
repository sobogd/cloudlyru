import 'dart:io';
import 'dart:isolate';

import 'package:crypto/crypto.dart' as crypto;

/// SHA-256 файла. Им сервер отличает дубли содержимого, а зеркало — «то же самое» от
/// «изменилось»; читаем потоком, потому что файлы бывают на гигабайты.
///
/// Пользуются им трое: очередь выгрузки (`queue/upload_runner.dart`) считает хэш перед заливкой,
/// движок зеркала (`mirror/mirror_engine.dart`) — тем же способом, поэтому хэши совпадают и
/// сервер узнаёт уже загруженный файл, и зеркало вниз (`mirror/mirror_pull.dart`) — чтобы
/// отличить «файл уже тот самый» от конфликта.
///
/// ## Где считается хэш: изолят, а не кадр интерфейса
///
/// `crypto` считает SHA-256 синхронно на каждый кусок, и вызов из UI-изолята — это чистая
/// работа процессора в том же тике, где рисуется кадр. На гигабайтном видео это заметные
/// рывки интерфейса, поэтому большой файл считается в отдельном изоляте ([Isolate.run]):
/// UI-изолят ждёт результат, ничего не считая. Мелкие файлы считаются на месте — подъём
/// изолята стоит дороже, чем хэш файла в сотню килобайт, а один кусок чтения такой файл
/// заканчивает целиком.
abstract final class Hasher {
  /// Размер куска чтения — 256 КиБ.
  ///
  /// Было 1 МиБ, и это оказалось много: обработка мегабайта — примерно 10 мс синхронной работы
  /// на кусок, то есть пропущенный кадр на каждом шаге, если считать в UI-изоляте. 256 КиБ
  /// (~2–3 мс) — компромисс, при котором чтение не превращается в сотни тысяч системных вызовов
  /// на файле в гигабайт (их ~4000), а кадр успевает нарисоваться между кусками.
  static const int _bufferBytes = 256 * 1024;

  /// С этого размера файл считается большим и хэшируется в отдельном изоляте.
  ///
  /// Мегабайт: ниже него хэш целиком укладывается в десяток миллисекунд, а подъём изолята
  /// (создание, копирование замыкания, завершение) стоит примерно столько же — на альбоме
  /// из тысяч мелких фото это была бы плата ни за что.
  static const int _isolateFromBytes = 1 << 20;

  /// SHA-256 файла [file] в виде шестнадцатеричной строки, как её ждёт сервер.
  ///
  /// Файл читается потоком, целиком в память не поднимается: на телефоне встречаются файлы
  /// в несколько гигабайт. Дескриптор закрывается всегда (`finally`), даже если чтение
  /// сорвалось, — иначе на большом обходе закончились бы дескрипторы.
  ///
  /// Побочных эффектов нет: файл только читается. Ошибки ввода-вывода и «файл исчез» бросаются
  /// исключением, а не возвращаются пустой строкой: пустая строка для вызывающих значит
  /// «содержимое другое» (для скачивания — ложное «не сошлось с хэшем», для очереди — лишняя
  /// выгрузка), и ошибку чтения они принимали за расхождение файлов. Ошибка видна там, где
  /// и должна быть — исключением с путём файла.
  static Future<String> sha256(File file) async {
    final path = file.path;
    // Нет файла — исключение отсюда же: считать хэш нечего, и вызывающий должен узнать это
    // до того, как начнёт читать
    final size = await file.length();
    if (size < _isolateFromBytes) return _digest(path);
    // Замыкание захватывает только путь (строку): объект File через границу изолята
    // не передаётся, а внутри создаётся заново по пути
    final (digest, error) = await Isolate.run(() => _digestOrError(path));
    if (digest != null) return digest;
    throw FileSystemException(error ?? 'хэш не посчитан', path);
  }

  /// Хэш в текущем изоляте: так считаются мелкие файлы.
  static String _digest(String path) {
    final (digest, error) = _digestOrError(path);
    if (digest != null) return digest;
    throw FileSystemException(error ?? 'хэш не посчитан', path);
  }

  /// Синхронный расчёт: возвращает пару «хэш или причина отказа».
  ///
  /// Пара, а не исключение, потому что вызывающий может быть другим изолятом: результат
  /// должен быть переносимым (`Isolate.run` отправляет его обратно сообщением), поэтому
  /// причина отказа — строка, а исключение с путём файла бросает уже вызывающий.
  static (String?, String?) _digestOrError(String path) {
    final sink = _DigestSink();
    final input = crypto.sha256.startChunkedConversion(sink);
    RandomAccessFile? raf;
    try {
      raf = File(path).openSync();
      while (true) {
        final chunk = raf.readSync(_bufferBytes);
        if (chunk.isEmpty) break;
        input.add(chunk);
      }
    } on FileSystemException catch (e) {
      // файл исчез, нет доступа, кончилось место в кэше чтения — всё это «хэш не посчитан»
      return (null, e.message.isEmpty ? 'файл не прочитан' : e.message);
    } finally {
      // дескриптор закрываем всегда, даже если чтение сорвалось: иначе на большом обходе
      // закончились бы дескрипторы, и следующий файл уже не открылся бы
      try {
        raf?.closeSync();
      } on FileSystemException catch (_) {}
      input.close();
    }
    final digest = sink.digest?.toString();
    // хэша нет — поток закрылся, не отдав результат; пустую строку возвращать нельзя
    return digest == null ? (null, 'хэш не посчитан') : (digest, null);
  }
}

/// Ловит итоговый [crypto.Digest] стримингового хеширования.
///
/// Пакет `crypto` отдаёт результат не возвратом, а последним событием потока, поэтому нужен
/// свой `Sink`: результат складывается в поле [digest], а [Hasher.sha256] забирает его после
/// закрытия потока.
class _DigestSink implements Sink<crypto.Digest> {
  crypto.Digest? digest;

  /// Вызывается один раз, при закрытии потока: событиями данные не приходят вовсе.
  @override
  void add(crypto.Digest data) => digest = data;

  /// Закрывать нечего: результат уже лежит в [digest], а ошибки чтения файла идут мимо sink.
  @override
  void close() {}
}
