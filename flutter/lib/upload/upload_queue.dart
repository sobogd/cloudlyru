import 'dart:async';

import 'package:file_picker/file_picker.dart';
import 'package:flutter/foundation.dart';

import '../api/cloudly_api.dart';

/// Состояние строки очереди загрузки.
///
/// Раньше состояние было сырой строкой (`'queued'`/`'done'`/…), и опечатка в нём не ловилась
/// ни компилятором, ни анализатором: строка молча не попадала ни в один фильтр очереди и
/// висела в панели как «ждущая». Enum убирает этот класс ошибок; в интерфейс состояние
/// по-прежнему отдаётся строкой ([UploadRow.state]) — панель загрузки сравнивает его с
/// `'done'`, `'failed'`, `'uploading'` и `'queued'`, и этот контракт не менялся.
enum UploadState { queued, uploading, done, failed }

/// Одна строка панели загрузки: файл, который положили в очередь, и его текущее состояние.
///
/// Меняет строку только очередь ([UploadQueue]) — поля закрыты, наружу отдаются геттеры.
/// Панель загрузки только читает: она перерисовывается по `notifyListeners`, а не правит
/// состояние сама.
class UploadRow {
  /// Порядковый номер, выданный очередью при добавлении файла ([UploadQueue._seq]).
  /// Панель загрузки рисует строки по порядку и на номер не смотрит: он нужен, чтобы отличить
  /// строки в логах и в отладчике, когда имена файлов совпадают.
  final int key;

  /// Путь к файлу на устройстве — по нему читает API. Строк с пустым путём очередь
  /// не грузит: так помечается файл, который прочитать нельзя (см. [UploadQueue.addFiles]).
  final String path;

  /// Имя файла, как его видит пользователь и как оно попадёт в облако.
  final String name;

  /// Размер в байтах. Берётся у выбранного файла при добавлении и дальше не переспрашивается;
  /// `0` — размер узнать не удалось (такой файл всё равно упадёт при чтении) или файл пустой.
  final int size;

  /// Папка в облаке, куда класть файл; `null` — корень.
  final String? folderId;

  UploadState _state = UploadState.queued;
  int _pct = 0;
  String? _phase;
  String? _note;
  String? _error;

  /// Строку отменили: она либо ждала своей очереди, либо грузилась в момент нажатия «отмена».
  /// Ждущие уходят из списка сразу, а грузящаяся — когда вернётся запрос: результат текущей
  /// передачи зависит от файла, и заранее неизвестно, успеет она или нет.
  bool _canceled = false;

  /// Создаёт строку очереди. Обязательны только те поля, без которых строку не с чем сравнивать
  /// и нечего качать ([key], [path], [name], [size]); остальные поля начала означают
  /// «файл ждёт своей очереди, ничего не происходило» и заполняются очередью по ходу загрузки.
  UploadRow({
    required this.key,
    required this.path,
    required this.name,
    required this.size,
    this.folderId,
  });

  /// Состояние строки строкой: `queued` | `uploading` | `done` | `failed`. Это контракт с
  /// панелью загрузки: она сравнивает значение ровно с этими строками и по ним же выбирает
  /// иконку и цвет.
  String get state => _state.name;

  /// Прогресс в процентах: 0 в начале, 100 у успешно загруженного.
  int get pct => _pct;

  /// Что происходит прямо сейчас: `hash`, `upload`, `relay` и подобное. Это фаза от API;
  /// в человеческий текст её переводит панель загрузки, а подробность фазы лежит в [note].
  String? get phase => _phase;

  /// Уточнение к текущей фазе (например, причина перехода на релей), приходит от API и
  /// показывается рядом со строкой.
  String? get note => _note;

  /// Текст ошибки, если загрузка не удалась. Заполняется только при `state == 'failed'`.
  String? get error => _error;
}

/// Общая очередь загрузки: живёт в AppState и переживает переключение вкладок.
///
/// Поведение своё, сверять его не с чем: очередь писалась как порт хука `useBulkUpload`
/// прежнего веб-клиента, но каталог `web/` из репозитория удалён, и источником истины
/// остался этот файл.
///
/// Зачем отдельный класс, а не код в экране «Файлы»: загрузка длится минутами и должна
/// продолжаться, когда человек ушёл в другой раздел, а вернувшись — увидеть те же строки и тот
/// же прогресс. Наружу очередь отдаёт только чтение строк ([rows], [busy]) и команды —
/// [addFiles], [cancel], [retryFailed], [dismissFailed], [reset]; панель ничего не запускает сама.
///
/// Файлы уходят по одному, последовательно: так прогресс и ошибки относятся к конкретной строке,
/// а не к пачке целиком. Ошибка одного файла не отменяет остальные, а выбор новых файлов во
/// время загрузки дописывается в тот же проход.
class UploadQueue extends ChangeNotifier {
  /// Как получить клиент API. Функция, а не готовый объект: `AppState.logout` заменяет клиент
  /// на новый (без старой cookie), а очередь при этом остаётся жить и должна ходить новым.
  final CloudlyApi Function() api;

  /// Принимает способ получить актуальный клиент API; сам клиент создаётся не здесь.
  UploadQueue(this.api);

  final List<UploadRow> _rows = [];

  /// Строки для панели загрузки: список только для чтения, чтобы интерфейс не мог вставить
  /// или выкинуть строку мимо очереди. Сами объекты строк живые — их поля очередь меняет на
  /// месте и уведомляет слушателей, а править их снаружи нельзя: поля закрыты.
  List<UploadRow> get rows => List.unmodifiable(_rows);

  /// Идёт ли проход очереди. Второй проход не запускается: он бы пошёл по тем же строкам, а
  /// новые выборы подхватывает текущий (см. [addFiles]).
  bool _running = false;
  int _seq = 0;

  /// Идёт ли работа: есть строки в ожидании или в загрузке. Именно по этому признаку панель
  /// показывает «загрузка N из M» и кнопку отмены.
  bool get busy => _rows.any((r) =>
      r._state == UploadState.queued || r._state == UploadState.uploading);

  /// Добавляет выбранные файлы в очередь и запускает загрузку. Ничего не возвращает.
  ///
  /// Принимает файлы из системного выбора файлов и папку в облаке ([folderId] == `null` —
  /// корень). Выбор во время уже идущей загрузки не теряется: строки дописываются в конец,
  /// а текущий проход подхватывает их, как только закончит файл, который грузит сейчас
  /// (раньше такой выбор молча отбрасывался, и человек был уверен, что файлы уехали).
  ///
  /// Файлы без пути (содержимое из чужого приложения: `PlatformFile.path` пуст, если URI не
  /// `file://`) загрузить нельзя, но и промолчать нельзя — каждый такой файл попадает в панель
  /// строкой с ошибкой: «повторить» её не возьмёт, а причину человек увидит.
  ///
  /// Побочные эффекты: убирает из панели строки, загруженные в прошлый раз, добавляет новые
  /// и уведомляет слушателей — панель появляется над списком файлов сразу.
  Future<void> addFiles(List<PlatformFile> files, String? folderId) async {
    if (files.isEmpty) return;
    // успешные строки прошлой партии — история, а не работа: место на экране освобождаем
    _rows.removeWhere((r) => r._state == UploadState.done);
    for (final f in files) {
      final p = f.path;
      if (p == null || p.isEmpty) {
        _rows.add(UploadRow(key: ++_seq, path: '', name: f.name, size: 0, folderId: folderId)
          .._state = UploadState.failed
          .._error = 'файл лежит не на устройстве: выбрать его для загрузки нельзя');
        continue;
      }
      // `lengthSync()` отдаёт размер, только если его сообщила нативная сторона; иначе
      // спрашиваем сам файл — иначе в панели стоял бы «0 Б» у непустого файла
      final len = f.lengthSync() ?? await f.length();
      _rows.add(UploadRow(
        key: ++_seq,
        path: p,
        name: f.name,
        size: len ?? 0,
        folderId: folderId,
      ));
    }
    notifyListeners();
    // не ждём: экран «Файлы» не должен блокироваться на время загрузки, прогресс придёт
    // уведомлениями. Если проход уже идёт, вызов выйдет сразу, а новые строки подберёт он же
    unawaited(_start());
  }

  /// Прогоняет очередь: берёт по одной строке в состоянии `queued` и грузит её, пока такие
  /// строки есть. Ничего не возвращает.
  ///
  /// Повторный вход защищён флагом [_running]: пока проход идёт, второй не начинается, поэтому
  /// [_start] можно звать из [addFiles] и [retryFailed] без разбирательств, кто уже запущен.
  /// Поиск следующей строки идёт на каждом круге — строки, добавленные или возвращённые
  /// в очередь во время передачи, попадают в этот же проход.
  ///
  /// Побочные эффекты: меняет состояние строк, уведомляет слушателей после каждой смены статуса
  /// и на каждом шаге прогресса, при отмене — вычищает помеченные отменёнными строки.
  Future<void> _start() async {
    if (_running) return;
    _running = true;
    try {
      for (;;) {
        // ищем заново на каждом круге: пока грузился файл, строки могли сменить состояние
        // (например, «повторить» вернуло упавшие в очередь) или исчезнуть при отмене
        final i = _rows.indexWhere((r) => r._state == UploadState.queued);
        if (i < 0) break;
        final row = _rows[i];
        row._state = UploadState.uploading;
        row._pct = 0;
        // примечание от прошлой попытки относится к прошлой попытке и сбивало бы с толку
        row._note = null;
        notifyListeners();
        try {
          await api().uploadFile(
            row.path,
            folderId: row.folderId,
            name: row.name,
            onProgress: (pct, phase, note) {
              row._pct = pct;
              row._phase = phase;
              row._note = note;
              notifyListeners();
            },
          );
          row._state = UploadState.done;
          row._pct = 100;
        } catch (e) {
          if (row._canceled) {
            // отменили, пока файл грузился: писать ему «не удалось» не за что — причина не в
            // файле, — поэтому строка просто исчезает, а не остаётся красной ошибкой
            _rows.remove(row);
          } else {
            // ошибку записываем в строку и идём дальше: один недоступный файл не должен
            // останавливать остальные, а причина остаётся видна рядом со строкой
            row._state = UploadState.failed;
            row._error = e.toString();
          }
        }
        notifyListeners();
      }
    } finally {
      _running = false;
      // уборка после отмены: помеченные строки, которые так и не загрузились, из списка уходят.
      // Отменённая строка удаляется по ссылке, а не по индексу, посчитанному до `await`:
      // за время передачи список менялся (отмена, новый выбор, «закрыть упавшие»)
      final before = _rows.length;
      _rows.removeWhere((r) => r._canceled && r._state != UploadState.done);
      if (_rows.length != before) notifyListeners();
    }
  }

  /// Отменяет загрузку: убирает из панели всё, что не успело загрузиться.
  ///
  /// Сам текущий файл не обрывается — [CloudlyApi.uploadFile] не умеет прерываться извне, —
  /// поэтому его строка исчезнет только когда запрос вернётся: успешная останется как
  /// загруженная, упавшая будет выброшена. Всё, что стояло в ожидании, уходит сразу;
  /// строки, добавленные (или возвращённые «повторить») уже после отмены, отменёнными не
  /// считаются и грузятся в этом же проходе.
  void cancel() {
    var marked = false;
    for (final r in _rows) {
      if (r._state == UploadState.queued || r._state == UploadState.uploading) {
        r._canceled = true;
        marked = true;
      }
    }
    if (!marked) return;
    _rows.removeWhere((r) => r._canceled && r._state == UploadState.queued);
    notifyListeners();
  }

  /// Ставит упавшие строки обратно в очередь и снова запускает загрузку.
  ///
  /// Счётчик и текст ошибки сбрасываются — это новая попытка, а не продолжение прежней.
  /// Если проход уже идёт, второй не запускается: текущий цикл сам подхватит строки, которые
  /// стали `queued`. Строки без пути не берём — их нечего грузить, и они остаются красными.
  void retryFailed() {
    for (final r in _rows) {
      if (r._state == UploadState.failed && r.path.isNotEmpty) {
        r._state = UploadState.queued;
        r._pct = 0;
        r._error = null;
        r._canceled = false;
      }
    }
    notifyListeners();
    unawaited(_start());
  }

  /// Убирает упавшие строки из панели — «понятно, закрыть».
  ///
  /// Только вид: файлы на устройстве и в облаке не трогаются, повторной попытки не будет.
  void dismissFailed() {
    _rows.removeWhere((r) => r._state == UploadState.failed);
    notifyListeners();
  }

  /// Полная очистка очереди — выход из аккаунта: строки не должны пережить смену пользователя.
  ///
  /// Незавершённые строки помечаются отменёнными, поэтому их не подберёт ни текущий проход, ни
  /// следующий. Уже начатая передача файла не обрывается — прервать её нечем, — но её результат
  /// никуда не попадёт: строка из списка ушла, а сессия к этому моменту погашена на сервере.
  void reset() {
    for (final r in _rows) {
      if (r._state == UploadState.queued || r._state == UploadState.uploading) {
        r._canceled = true;
      }
    }
    _rows.clear();
    notifyListeners();
  }
}
