import 'dart:async';

import 'package:flutter/foundation.dart';

import 'api/cloudly_api.dart';
import 'api/models.dart';
import 'storage/settings.dart';
import 'sync/sync_controller.dart';
import 'upload/upload_queue.dart';

/// Глобальное состояние: адрес сервера, токен, текущий пользователь.
///
/// Здесь же живёт очередь загрузки файлов ([uploads]) — она общая на всё приложение, поэтому
/// переживает переключение вкладок и уход с экрана «Файлы».
///
/// Объект создаётся один раз в `main` (и переопределяет `appStateProvider`) и живёт до конца
/// процесса: выход из аккаунта его не уничтожает, а возвращает в состояние «пользователя нет».
/// Изменения рассылаются через [notifyListeners] — на них перестраивается корень приложения
/// и разделы.
///
/// Чего здесь намеренно нет: самого синхронизатора. Он тяжёлая подсистема со своими базами и
/// живёт в провайдере, а сюда только подключается ([attachSync]) — так порядок «сначала вход,
/// потом синхронизация» остаётся в одном месте.
class AppState extends ChangeNotifier {
  final Settings settings;
  CloudlyApi api;

  /// Текущий пользователь; `null` — вход не выполнен, и корень приложения показывает экран входа.
  UserInfo? user;

  /// Идёт ли ещё восстановление входа при запуске. Взводится в конструкторе и снимается в
  /// [restore], поэтому `true` означает «мы ещё не знаем, есть ли пользователь» — в этом
  /// состоянии корень показывает прогресс, а не экран входа.
  bool checking = true;

  /// Клиент API создаётся сразу по адресу из настроек, ещё до всякой сессии: адрес известен
  /// всегда, а cookie добавляется позже — при восстановлении входа ([restore]) или при входе.
  AppState(this.settings) : api = CloudlyApi(serverUrl: settings.serverUrl);

  /// Очередь ручной загрузки файлов: её наполняет кнопка «Загрузить файлы» на экране «Файлы»,
  /// а показывает панель `UploadPanel` там же.
  ///
  /// Клиент отдаётся замыканием, а не значением: [logout] заменяет [api] на свежий, и очередь
  /// должна ходить новым клиентом, а не тем, что был при создании. `late final` — чтобы
  /// замыкание не тронуло [api] до завершения конструктора.
  late final UploadQueue uploads = UploadQueue(() => api);

  /// Синхронизатор: он не часть интерфейса, а отдельная подсистема со своими базами,
  /// поэтому живёт в провайдере, а сюда только подключается (см. [attachSync]).
  SyncController? _sync;

  /// Привязка синхронизатора. Провайдер строится при первом чтении из корня приложения,
  /// поэтому при уже готовом входе синхронизация стартует тут же — иначе она ждала бы
  /// следующего события, которого при запуске приложения не будет.
  ///
  /// Вызывается из `CloudlyApp.initState` — ровно один раз на корень, а не из `build`:
  /// привязка запускает подсистему (базы, токен устройства, наблюдение за папками), и делать
  /// это в сборке виджета нельзя. Первая же проверка — на тот же объект: повторная привязка
  /// не должна заново запускать синхронизацию.
  /// Побочный эффект: при готовом входе асинхронно стартует [SyncController.start] —
  /// с текущим [api] и логином пользователя.
  void attachSync(SyncController sync) {
    if (identical(_sync, sync)) return;
    _sync = sync;
    // вход мог быть восстановлен ещё до того, как провайдер построил синхронизатор, —
    // тогда стартовать нужно прямо здесь, иначе синхронизация не начнётся до входа в аккаунт
    if (user != null) unawaited(_startSync());
  }

  /// Синхронизация начинается только со входом: без сессии у неё нет ни токена устройства,
  /// ни облака, куда лить.
  ///
  /// Логин и [api] запоминаются на момент вызова: `start` выпускает по ним токен устройства и
  /// дальше работает уже своим клиентом. Повторный вызов безопасен — [SyncController.start]
  /// сам игнорирует повторный запуск.
  Future<void> _startSync() async {
    final sync = _sync;
    final current = user;
    if (sync == null || current == null) return;
    await sync.start(api, current.login);
  }

  /// Восстановление входа при запуске приложения: если в настройках лежит cookie сессии,
  /// подставляем её в клиент и спрашиваем `/auth/me`.
  ///
  /// Побочные эффекты: заполняет [user], при успехе запускает синхронизацию, снимает [checking]
  /// и уведомляет слушателей — именно по `checking` корень приложения решает, показывать ли
  /// прогресс, экран входа или оболочку.
  ///
  /// Вызывается из `main` уже после `runApp` и без ожидания: в сеть здесь уходит `/auth/me`
  /// с таймаутами 20 с на подключение и 60 с на ответ, и ждать этого до первого кадра значило
  /// бы показывать нативную заставку до полутора минут при «чёрной дыре» в сети. Пока запрос
  /// идёт, корень держит `checking == true` и показывает прогресс.
  ///
  /// Сбой запроса не считается ошибкой входа: сессия могла протухнуть, а сеть — пропасть.
  /// Cookie при этом остаётся на месте — её снимает только явный выход ([logout]), иначе
  /// временная проблема с сетью заставляла бы вводить пароль заново.
  Future<void> restore() async {
    final s = settings.session;
    if (s != null && s.isNotEmpty) {
      api.session = s;
      try {
        user = await api.me();
      } catch (_) {
        user = null;
      }
    }
    // Порядок с `attachSync` не гарантирован: привязка идёт из `initState` корня, а этот метод
    // уже в фоне. Кто из них второй — тот и запускает синхронизацию, повторный запуск
    // [SyncController.start] игнорирует.
    if (user != null) await _startSync();
    checking = false;
    notifyListeners();
  }

  /// Меняет адрес сервера и пересобирает клиент API.
  ///
  /// Нужен экрану входа: адрес вводится там же, где логин, — иначе смена домена сделала бы
  /// установленное приложение неработоспособным без переустановки. Возвращает `true`, если
  /// адрес изменился. Сессию не трогает: на новом сервере она недействительна, и вход всё
  /// равно пойдёт по новой.
  Future<bool> useServer(String url) async {
    final next = url.trim();
    if (next.isEmpty || next == settings.serverUrl) return false;
    await settings.setServerUrl(next);
    // Свежий клиент, а не правка поля: Dio собран один раз под свой baseUrl, и смена адреса
    // в поле уводила бы запросы на старый адрес, а ссылки на файлы — на новый.
    api = CloudlyApi(serverUrl: settings.serverUrl);
    return true;
  }

  /// Вход логином и паролем.
  ///
  /// Принимает логин (уже без пробелов по краям — их срезает экран входа) и пароль; ничего не
  /// возвращает. Побочные эффекты: подставляет cookie в [api], читает пользователя через
  /// `/auth/me`, сохраняет cookie в настройки и запускает синхронизацию.
  ///
  /// Ошибку не глотает: исключение уходит наверх в экран входа, который показывает текст под
  /// полями. Порядок важен: cookie записывается в настройки последней, уже после успешного
  /// `/auth/me`. Раньше она сохранялась до него, и падение `me()` (сеть, отдыхающий сервер)
  /// оставляло в prefs живую сессию при том, что вход показался неудачным, — при следующем
  /// запуске приложение входило в аккаунт «само».
  Future<void> login(String login, String password) async {
    // свежий клиент: вход не должен утащить старую сессию
    final fresh = CloudlyApi(serverUrl: settings.serverUrl);
    final cookie = await fresh.login(login, password);
    api.session = cookie;
    final me = await api.me();
    await settings.setSession(cookie);
    user = me;
    notifyListeners();
    await _startSync();
  }

  /// Перечитывает пользователя (`/auth/me`) — нужен после смены логина в настройках.
  ///
  /// Побочно: обновляет [user] и уведомляет слушателей. Логин показан в настройках из этого
  /// состояния, и без перечитки он оставался бы прежним до следующего запуска приложения.
  /// Ошибку глотаем: логин на сервере уже новый, а неудачная перечитка — повод показать старое
  /// значение в подписи, а не сорвать работу экрана.
  Future<void> reloadUser() async {
    try {
      user = await api.me();
      notifyListeners();
    } catch (_) {}
  }

  /// Выход из аккаунта: гасит синхронизацию, гасит сессию на сервере, стирает cookie из
  /// настроек и возвращает состояние к «пользователя нет».
  ///
  /// Порядок шагов не произвольный. Синхронизатор идёт первым, потому что он отзывает токен
  /// устройства, а тот даёт полный доступ к облаку: пока он жив, выход из приложения ничего
  /// не значит. Затем — серверный `/auth/logout` для веб-сессии: его сбой не должен мешать
  /// выходу, поэтому исключение здесь глушится.
  ///
  /// Клиент API заменяется новым, чтобы в нём не осталось старой cookie. Вместе с сессией
  /// стирается всё, что принадлежит вышедшему человеку: сохранённая вкладка ([Settings.ui])
  /// и строки очереди загрузки — иначе следующий пользователь получил бы вкладку предыдущего
  /// и его имена файлов в панели загрузки. Уведомление слушателей в конце переключает корень
  /// приложения обратно на экран входа.
  Future<void> logout() async {
    // первым делом синхронизатор: он отзывает свой токен устройства, а тот даёт полный
    // доступ к облаку мимо приложения и без веб-сессии
    await _sync?.signOut();
    try {
      await api.logout();
    } catch (_) {}
    await settings.clearSession();
    await settings.ui.clear();
    // начатую передачу файла прервать нечем, но её результат никому не нужен: строки уходят
    // из панели, а сессия к этому моменту погашена на сервере
    uploads.reset();
    api = CloudlyApi(serverUrl: settings.serverUrl);
    user = null;
    notifyListeners();
  }
}
