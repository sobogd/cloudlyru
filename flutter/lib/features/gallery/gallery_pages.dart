import 'dart:async';

import 'package:flutter/foundation.dart';

import '../../api/models.dart';
import 'data/gallery_store.dart';

/// Кадры галереи, прочитанные из локального индекса в память целиком.
///
/// ## Почему все, а не окно пачек
///
/// Раньше кадры читались пачками по двести и держались в памяти последними двадцатью четырьмя
/// пачками: строка сетки адресовалась месяцем и номером кадра, а сам кадр под этим адресом
/// появлялся только после чтения. Отсюда и брались серые клетки на прокрутке: движение списка
/// чтение приостанавливало, и ползунок, протянутый через всю библиотеку, ехал по пустым клеткам,
/// а кадры доезжали уже после остановки.
///
/// Теперь библиотека читается один раз при открытии раздела ([loadAll]) и лежит в памяти
/// месяцами. Пятьдесят шесть тысяч кадров — это около двадцати пяти мегабайт (кадр без картинки
/// это id, имя, mime, хэш, дата съёмки и размер, то есть сотни байт), и зато у сетки не бывает
/// клетки, про которую неизвестно, что там: [itemAt] отвечает из памяти, и прокрутка в базу
/// не ходит вовсе.
///
/// ## Что осталось от пачек
///
/// Месяц — единица хранения и перечитывания. Номер кадра внутри месяца по-прежнему единственный
/// адрес, который есть у строки без чтения данных (строка × четыре клетки, см. `GalleryIndex.specAt`),
/// поэтому список кадров нарезан по месяцам, а не лежит одной лентой: по месяцу же и понятно,
/// что перечитывать после синхронизации ([refreshChanged]) — лента дописывает кадры в конец
/// месяца и снимает удалённые, и у остальных месяцев в памяти уже верное.
///
/// Картинок здесь нет и не будет: это кадры ленты, а не превью (см. `ThumbCache`).
class GalleryPages {
  GalleryPages({
    required this.store,
    required this.tzOffsetMin,
    required this.onLoaded,
    required this.onError,
  });

  /// Сколько кадров просим у базы одной страницей при чтении месяца.
  ///
  /// Тысяча — компромисс между числом запросов и размером промежуточного списка: строка таблицы
  /// в виде карты весит около килобайта, и месяц в десять тысяч кадров, прочитанный одним
  /// запросом, дал бы лишние десять мегабайт мусора.
  static const int _chunk = 1000;

  /// Локальный индекс — источник кадров.
  final GalleryStore store;

  /// Пояс, в котором посчитаны ключи месяцев: с ним же читаются границы месяца.
  final int tzOffsetMin;

  /// Кадры приехали — владельцу есть что перерисовать.
  final VoidCallback onLoaded;

  /// Месяц не прочитался (сбой базы): владелец показывает причину и даёт повторить.
  final ValueChanged<Object> onError;

  /// Кадры по месяцам: ключ — «ГГГГ-ММ», пустая строка — кадры без даты. Порядок внутри
  /// списка тот же, что у ленты: от свежих к старым.
  final Map<String, List<MediaItem>> _byMonth = {};

  /// Месяцы, которые читаются прямо сейчас: повторная просьба только дублировала бы запрос.
  final Set<String> _reading = {};

  /// Месяцы, снятые из памяти во время чтения: их ответ уже не годится (см. [dropMonth]).
  final Set<String> _stale = {};

  /// Идёт первое чтение всей библиотеки.
  ///
  /// Просьбы отдельных месяцев в это время пропускаются: их всё равно накроет полное чтение,
  /// а дописывание в карту из двух запросов сразу оставило бы в памяти усечённый месяц.
  bool _loadingAll = false;

  /// Чтение приостановлено: список едет (см. `GalleryController`).
  ///
  /// Теперь это значит немного: библиотека лежит в памяти, и читать на ходу почти нечего.
  /// Осталось для тех месяцев, которых в памяти ещё нет или которые перечитываются после
  /// наполнения индекса: пока палец двигает список, их никто не ждёт. Уже прочитанное
  /// отдаётся как обычно — месяц в памяти это не запрос.
  bool paused = false;

  /// Прочитать всю библиотеку: кадры всех месяцев в память.
  ///
  /// Зовётся при открытии раздела и не блокирует первый кадр сетки: геометрия строится по
  /// разбивке и показывается сразу, а кадры наполняют её следом (см. `GalleryController.open`).
  ///
  /// Побочно: заполняет [_byMonth] и зовёт [onLoaded], когда кадры на месте.
  Future<void> loadAll() async {
    _loadingAll = true;
    try {
      final all = await store.allItemsByMonth(tzOffsetMin: tzOffsetMin);
      _byMonth
        ..clear()
        ..addAll(all);
      onLoaded();
    } catch (e) {
      onError(e);
    } finally {
      _loadingAll = false;
    }
  }

  /// Кадр по номеру [offset] внутри месяца [month]; `null` — кадра в памяти нет.
  ///
  /// Заодно просит месяц, которого в памяти нет вовсе: отдельного расчёта видимости не нужно
  /// именно потому, что зовут это построенные строки — спросили, значит клетка сейчас на экране.
  ///
  /// Прочитанный ПУСТЫМ месяц заново не просится: иначе пустой ответ заказывал бы следующий
  /// запрос и на непустом по разбивке месяце это был бы бесконечный цикл чтения с перерисовкой
  /// на каждом круге. Такие месяцы догружает [refreshChanged] — по шагам наполнения индекса.
  MediaItem? itemAt(String month, int offset) {
    if (offset < 0) return null;
    final list = _byMonth[month];
    if (list == null) {
      if (!paused) _request(month);
      return null;
    }
    return offset < list.length ? list[offset] : null;
  }

  /// Кадр по номеру [offset] внутри месяца [month] без чтения: `null` — кадра в памяти нет.
  ///
  /// Нужен опросу состояний превью: он смотрит, что видно, но ничего не грузит (см.
  /// `GalleryController.pollStatuses`).
  MediaItem? loadedAt(String month, int offset) {
    if (offset < 0) return null;
    final list = _byMonth[month];
    return (list != null && offset < list.length) ? list[offset] : null;
  }

  /// Заменить кадр в памяти — новое состояние превью (ответ `/media/status`).
  ///
  /// Возвращает `true`, если замена нашла своё место: месяц мог перечитываться, и тогда менять
  /// нечего — следующее чтение принесёт свежее состояние из индекса.
  bool replace(String month, int offset, MediaItem item) {
    final list = _byMonth[month];
    if (list == null || offset < 0 || offset >= list.length) return false;
    list[offset] = item;
    return true;
  }

  /// Забыть месяц [month] и прочитать его заново: кадр из него удалён, и номера внутри месяца
  /// сдвинулись.
  ///
  /// Перечитывается сразу, не дожидаясь остановки списка: удаление — действие человека, а не
  /// фоновая догрузка, и месяц возвращается в память через один запрос, тогда как отложенное
  /// чтение оставило бы его клетки заглушками до следующего движения пальца.
  ///
  /// Если месяц читается прямо сейчас, его ответ не годится: чтение началось ДО удаления и
  /// вернуло бы удалённый кадр обратно в память. Такой месяц помечается устаревшим и читается
  /// заново, как только нынешнее чтение закончится ([_read]).
  void dropMonth(String month) {
    _byMonth.remove(month);
    if (_reading.contains(month)) {
      _stale.add(month);
      return;
    }
    _request(month, force: true);
  }

  /// Перечитать месяцы, у которых число кадров разошлось с разбивкой: синхронизация дописала
  /// кадры в конец месяца или сняла удалённые.
  ///
  /// Сравнение по числу кадров и есть то, что делает это дешёвым: у месяцев, где ничего
  /// не менялось, перечитывать нечего, а во время наполнения индекса меняется ровно тот месяц,
  /// который лента дочитывает сейчас. Месяцев, которых в памяти ещё нет, это не касается:
  /// их просят построенные строки, то есть видимое место.
  ///
  /// Побочно: месяцы, пропавшие из разбивки (кадры удалили целиком), снимаются из памяти.
  void refreshChanged(List<MediaMonthBucket> months) {
    if (_loadingAll || months.isEmpty) return;
    final known = {for (final m in months) m.month ?? ''};
    _byMonth.removeWhere((key, list) => list.isNotEmpty && !known.contains(key));
    for (final m in months) {
      final key = m.month ?? '';
      final list = _byMonth[key];
      // Месяца в памяти нет вовсе — его не читали: такой просят построенные строки, то есть
      // видимое место. Остаются те, что уже читались: у них либо разошлось число кадров, либо
      // чтение пришлось на время, когда наполнение индекса до этих кадров ещё не дошло
      // (пустой список) — и то и другое значит «в памяти версии нет».
      if (list == null || list.length == m.count) continue;
      _request(key);
    }
  }

  /// Попросить месяц [month]: читаемые и уже прочитанные пропускаются.
  ///
  /// [force] — просьба важнее всего остального: она идёт от удаления кадра, где месяц снят
  /// из памяти намеренно, и ждать остановки списка ей нечего.
  void _request(String month, {bool force = false}) {
    if (_reading.contains(month)) return;
    if (!force && (_loadingAll || _byMonth.containsKey(month))) return;
    unawaited(_read(month));
  }

  /// Прочитать все кадры месяца и положить их в память одним списком.
  ///
  /// Список собирается целиком и подменяет прежний одним движением: месяц, показанный половиной,
  /// мигал бы заглушками на каждой дописанной странице. Ошибка чтения оставляет в памяти прежний
  /// список — он лучше пустоты, а причина уходит владельцу ([onError]).
  ///
  /// Побочно: [_reading] на время чтения (по нему просьбы не дублируются) и [onLoaded], когда
  /// кадры на месте.
  Future<void> _read(String month) async {
    _reading.add(month);
    try {
      final items = <MediaItem>[];
      while (true) {
        final page = await store.monthItems(
          month,
          tzOffsetMin: tzOffsetMin,
          offset: items.length,
          limit: _chunk,
        );
        items.addAll(page);
        if (page.length < _chunk) break;
      }
      _byMonth[month] = items;
      onLoaded();
    } catch (e) {
      onError(e);
    } finally {
      _reading.remove(month);
      // Пока читали, месяц сняли из памяти (удалён кадр): прочитанное устарело — читаем снова.
      if (_stale.remove(month)) unawaited(_read(month));
    }
  }
}
