import '../../api/models.dart';

/// Строка сетки галереи: либо заголовок месяца, либо ряд кадров, либо строка состояния.
///
/// Строками, а не одной плиткой на кадр, сетка собирается ради заголовков месяцев: заголовок —
/// такая же строка, и он не может разорвать ряд кадров. Готовит строки
/// `GalleryController` по геометрии `GalleryIndex`, а вёрстка (`GalleryScreen`) только
/// раскладывает то, что в них лежит.
class GalleryRow {
  /// Подпись заголовка («Май 2021»); у ряда кадров и строки состояния — `null`.
  final String? header;

  /// Клетки ряда: `null` — кадр этого места ещё не прочитан из локального индекса.
  ///
  /// Пустая клетка здесь не ошибка, а обычное состояние: строки строятся сразу на всю историю,
  /// а кадры читаются только для тех, что попали в видимое место. Клетка на своём месте
  /// с самого начала — поэтому появление кадра ничего не сдвигает.
  final List<MediaItem?> items;

  /// Номер первого кадра ряда во всей ленте; у заголовка и строки состояния `-1`.
  ///
  /// По нему открывается просмотрщик: он листает кадры по номерам, и номер клетки — это
  /// `firstItem` плюс её место в ряду.
  final int firstItem;

  /// Высота строки: у заголовка своя ([GalleryGrid.headerHeight]), у ряда кадров — шаг ряда
  /// (сторона клетки плюс зазор), у строки состояния — своя ([GalleryGrid.noteHeight]).
  ///
  /// Фиксированные высоты здесь принципиальны: по ним вёрстка считает полную высоту списка
  /// и переводит позицию прокрутки в строку, никого не спрашивая и ничего не измеряя.
  final double height;

  /// Текст строки состояния в конце списка («Загружаем историю…», причина сбоя) — `null`
  /// у остальных строк.
  final String? note;

  const GalleryRow.header(String this.header, this.height)
      : items = const [],
        firstItem = -1,
        note = null;

  const GalleryRow.items(this.items, this.firstItem, this.height)
      : header = null,
        note = null;

  const GalleryRow.note(String this.note, this.height)
      : header = null,
        items = const [],
        firstItem = -1;

  /// Заголовок ли это (у ряда кадров подписи нет).
  bool get isHeader => header != null;

  /// Строка состояния ли это.
  bool get isNote => note != null;
}

/// Геометрия сетки: сколько кадров в ряду и какие у строк высоты.
///
/// Числа одни на весь раздел: по ним и вёрстка, и расчёт видимого места, и место чтения
/// при пересборке геометрии. Разъехавшись, они дали бы список, посчитанный по одной геометрии
/// и нарисованный по другой, —
/// а это ровно тот «скролл уезжает», из-за которого раздел и переписывался.
///
/// Число колонок — функция ширины экрана: телефон в портрете показывает четыре кадра в ряд,
/// планшет и десктоп — больше. Функция одна на весь раздел, и считает её контроллер по той
/// же ширине, от которой считаются высота клеток и полная длина списка, — поэтому геометрия
/// всегда одна, а не «посчитана по четырём, а нарисована по шести».
class GalleryGrid {
  const GalleryGrid._();

  /// Кадров в ряду при ширине сетки [width] (логические пиксели).
  ///
  /// Пороги — про превью, а не про плотность. Сервер собирает превью сетки одним квадратом
  /// `GRID_SIZE = 256` (src/media/media.service.ts), и клетка не должна уходить в заметный
  /// апскейл: при DPR 3 клетка в N колонок на ширине W — это `3W/(N+1)` физических пикселей,
  /// и при 256 px это
  ///
  ///  * 4 колонки: до 373 dp (телефон в портрете — 360–393 dp, как раньше);
  ///  * 5 колонок: до 459 dp (широкий телефон, маленький планшет в портрете);
  ///  * 6 колонок: до 574 dp (планшет в портрете, узкое окно);
  ///  * 7 колонок: до 689 dp (широкий планшет);
  ///  * 8 колонок: шире (десктоп; на Retina-маке клетка в 8 колонок ~125–190 px — без апскейла).
  ///
  /// Выше DPR (4) запас меньше, но и экраны шире: на 480 dp при DPR 4 клетка в 5 колонок
  /// ~320 px — всё равно покрывается квадратом. Ниже 4 колонок уходить нельзя: превью 256
  /// уже не покрывает клетку, а сервер другой размер не отдаёт.
  static int columnsFor(double width) {
    if (width >= 690) return 8;
    if (width >= 575) return 7;
    if (width >= 460) return 6;
    if (width >= 374) return 5;
    return 4;
  }

  /// Зазор между клетками и по краям сетки.
  ///
  /// Он же — отступ списка сверху: позиция прокрутки отсчитывается от начала содержимого,
  /// и контроллер прибавляет этот отступ, переводя строку в позицию (см.
  /// `GalleryController.topInset`). Значение одно на оба места намеренно: разойдясь, они
  /// увели бы позицию мимо строки на величину зазора.
  static const double gap = 3.0;

  /// Зазор справа под ползунок скроллбара.
  ///
  /// Ползунок рисуется поверх списка у самого края, и без этого зазора он лёг бы на последний
  /// столбец. Десяти точек хватает с запасом: на Android ползунок тонкий (4 dp, см.
  /// `Scrollbar`), а при наведении мыши (настольная сборка) он шире — 12 dp, и тогда он
  /// занимает зазор целиком, не задевая клеток.
  static const double scrollbarInset = 10.0;

  /// Высота строки-заголовка месяца вместе с отступом.
  static const double headerHeight = 34.0;

  /// Высота строки состояния в конце списка: в две строки текста — причина сбоя бывает длинной.
  static const double noteHeight = 60.0;

  /// Сторона клетки при ширине сетки [width]: экран минус зазор под ползунок и зазоры сетки,
  /// поделённый на колонки. Колонки — по той же ширине, что и сторона, поэтому сторона и
  /// число колонок никогда не разъезжаются.
  static double cellSide(double width) => (width - (columnsFor(width) + 1) * gap) / columnsFor(width);

  /// Шаг ряда: сторона клетки плюс зазор. По нему считается высота ряда кадров.
  static double rowStep(double width) => cellSide(width) + gap;
}
