/// Форматтеры панели очереди превью: разряды в числах задач и срок остатка.
///
/// Файл общий для двух мест: панели очереди на экране настроек (`QueuePanel`) и отдельного
/// экрана ошибок (`QueueErrorsScreen`) — срок и разряды в них должны считаться одинаково.
///
/// Разряды считает `intl` (он уже в зависимостях приложения), а не `fmt` из
/// `util/format.dart`: там форматтер размера, он переводит число в килобайты и мегабайты,
/// а здесь числа означают количество задач — «осталось: 12 345», а не «12 345 КБ».
library;

import 'package:intl/intl.dart';

import '../../api/models.dart';

/// Разделитель разрядов в числах: «12345» → «12 345».
///
/// Локаль задана явно, а не взята из системы: подпись не должна зависеть от языка телефона,
/// а весь интерфейс русский. Раскладка одна на оба экрана — иначе одно и то же число
/// выглядело бы в них по-разному.
final _digits = NumberFormat.decimalPattern('ru');

/// Число задач с разделёнными разрядами: сервер отдаёт их без форматирования, а «12 345»
/// читается заметно лучше, чем «12345».
String groupDigits(int n) => _digits.format(n);

/// Срок на остаток очереди: точность до минут не нужна, поэтому секунды → минуты → часы → сутки.
String? eta(int? sec) {
  if (sec == null || sec <= 0) return null;
  if (sec < 90) return '$sec с';
  if (sec < 5400) return '${(sec / 60).round()} мин';
  if (sec < 48 * 3600) return '${(sec / 3600).round()} ч';
  return '${(sec / 86400).round()} сут';
}

/// « (≈ 4 сут)» рядом с числом остатка: сервер считает срок по медиане длительности задач,
/// и пока замеров нет — не показываем ничего.
String etaSuffix(QueueStatus q, String kind) {
  final e = eta(q.estimates[kind]?.etaSec);
  return e == null ? '' : ' (≈ $e)';
}
