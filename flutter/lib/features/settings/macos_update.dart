import 'dart:io';

import 'package:path/path.dart' as p;

/// Заменить работающую настольную сборку новой и запустить её заново (только macOS).
///
/// На Android обновление отдаётся системе (`open_filex` → установщик APK), а на маке установщика
/// нет: приложение обязано подменить само себя. Подменить бандл работающего приложения нельзя —
/// поэтому работа разбита на две части: приложение кладёт рядом скрипт-помощник и уходит,
/// а помощник уже после его выхода распаковывает [zip], ставит новую сборку на место прежней
/// и запускает её.
///
/// Почему помощник — обычный `sh`, а не нативный код: подменить каталог и запустить приложение
/// умеют `ditto`, `mv` и `open` из системы, и держать ради этого Swift в проекте незачем.
///
/// ## Что проверяется до выхода приложения
///
/// * сборка лежит там, куда есть запись: если приложение поставили в чужой каталог, подмена
///   провалилась бы уже после выхода, и человек остался бы без приложения. Проба на запись
///   делается заранее, и её провал — исключение наружу, а не тихая подмена;
/// * в архиве есть `Cloudly.app`: помощник ищет любой `*.app` в корне распаковки.
///
/// ## Что будет, если помощник споткнётся
///
/// Прежняя сборка сдвигается в `<бандл>.old`, а не удаляется: если новую поставить не удалось,
/// помощник возвращает старую и всё равно запускает приложение. Ход замены пишется в лог рядом
/// с архивом (`replace.log`) — экрана у помощника нет, а разбираться с неудачей придётся руками.
///
/// ## Про карантин
///
/// Архив качает само приложение обычным HTTP-клиентом, поэтому флага `com.apple.quarantine`
/// на нём не появляется, и Gatekeeper заменённую сборку не блокирует. Сборка, скачанная
/// браузером, была бы помечена — тогда её пришлось бы снимать руками.
///
/// @param zip скачанный и проверенный (размер, sha256) архив со сборкой.
/// Побочные эффекты: файлы во временном каталоге, запущенный отсоединённый помощник и
/// **выход из приложения** ([exit]) — эта функция не возвращается.
Future<Never> installMacosUpdate(File zip) async {
  if (!Platform.isMacOS) {
    throw UnsupportedError('подмена сборки поддерживается только на macOS');
  }
  final bundle = _bundlePath();
  _checkWritable(bundle);

  final work = Directory.systemTemp.createTempSync('cloudly-update');
  final unpacked = p.join(work.path, 'unpacked');
  final log = p.join(work.path, 'replace.log');
  final script = File(p.join(work.path, 'replace.sh'));
  await script.writeAsString(
    _script(
      pid: pid,
      zip: zip.path,
      bundle: bundle,
      unpacked: unpacked,
      log: log,
    ),
  );
  // Права на запуск: `sh` читает файл и без них, но так скрипт можно запустить и руками,
  // если автоматическая замена почему-то не пошла
  await Process.run('chmod', ['+x', script.path]);

  // Отсоединённый процесс: помощник обязан пережить выход приложения, иначе он умрёт вместе
  // с ним на первой же итерации ожидания
  await Process.start('/bin/sh', [script.path], mode: ProcessStartMode.detached);
  // Выходим сразу: помощник ждёт именно этого. `exit` вместо аккуратного закрытия окон —
  // намеренно: приложение всё равно перезапустится, а ждать закрытия всех ресурсов здесь
  // значит держать помощника в ожидании
  exit(0);
}

/// Путь к бандлу работающего приложения: `Platform.resolvedExecutable` — это
/// `<бандл>.app/Contents/MacOS/<имя>`, поэтому каталог бандла — три уровня вверх.
String _bundlePath() {
  final exe = Platform.resolvedExecutable;
  final macosDir = p.dirname(exe); // …/Contents/MacOS
  final contents = p.dirname(macosDir); // …/Contents
  return p.dirname(contents); // …/Cloudly.app
}

/// Проверить, что рядом со сборкой можно писать: иначе подмена провалится после выхода.
///
/// Проба — временный файл рядом с бандлом: она проверяет ровно то, что понадобится помощнику
/// (`mv` старой сборки в сторону и `mv` новой на её место).
void _checkWritable(String bundle) {
  final parent = Directory(p.dirname(bundle));
  final probe = File(p.join(parent.path, '.cloudly-update-probe'));
  try {
    probe.writeAsStringSync('');
    probe.deleteSync();
  } catch (_) {
    throw Exception(
      'нет прав на запись в ${parent.path}: перенесите Cloudly.app туда, где можно писать '
      '(например, в /Applications), и повторите обновление',
    );
  }
}

/// Текст помощника: ожидание выхода, распаковка, подмена бандла, запуск.
///
/// Все пути подставляются в одинарных кавычках ([_q]): в путях macOS бывают пробелы, и без
/// экранирования скрипт развалился бы на первом же «/Users/Иван Иванов».
String _script({
  required int pid,
  required String zip,
  required String bundle,
  required String unpacked,
  required String log,
}) {
  final q = _q;
  return '''
#!/bin/sh
# Помощник обновления Cloudly: ждёт выхода приложения, ставит новую сборку на место прежней
# и запускает её. Написан приложением перед выходом, живёт до конца замены.
set -u
exec >>${q(log)} 2>&1
echo "=== замена сборки запущена ==="

# Работать с бандлом работающего приложения нельзя: ждём, пока процесс уйдёт
while kill -0 ${q(pid.toString())} 2>/dev/null; do
  sleep 0.5
done

rm -rf ${q(unpacked)}
mkdir -p ${q(unpacked)} || { echo "не удалось создать каталог распаковки"; exit 1; }

if ! ditto -x -k ${q(zip)} ${q(unpacked)}; then
  echo "распаковать архив не удалось — оставляю прежнюю сборку"
  open ${q(bundle)}
  exit 1
fi

# Имя сборки в архиве может отличаться (сборка переименована) — берём любой .app в корне
NEW=\$(find ${q(unpacked)} -maxdepth 1 -name '*.app' -print -quit)
if [ -z "\$NEW" ]; then
  echo "в архиве нет .app — оставляю прежнюю сборку"
  open ${q(bundle)}
  exit 1
fi

OLD=${q('$bundle.old')}
rm -rf "\$OLD"
if ! mv ${q(bundle)} "\$OLD"; then
  echo "прежнюю сборку сдвинуть не удалось — оставляю как есть"
  open ${q(bundle)}
  exit 1
fi
if ! mv "\$NEW" ${q(bundle)}; then
  echo "новую сборку поставить не удалось — возвращаю прежнюю"
  mv "\$OLD" ${q(bundle)}
  open ${q(bundle)}
  exit 1
fi
rm -rf "\$OLD"
open ${q(bundle)}
echo "готово"
''';
}

/// Значение для подстановки в скрипт: одинарные кавычки с экранированием вложенных.
///
/// Внутри одинарных кавычек `sh` не разбирает ничего, кроме самой кавычки, поэтому это
/// единственный способ подставить путь без сюрпризов; вложенная кавычка закрывается,
/// экранируется и открывается снова (`'` → `'\''`).
String _q(String value) => "'${value.replaceAll("'", r"'\''")}'";
