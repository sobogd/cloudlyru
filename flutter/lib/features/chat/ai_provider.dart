import 'ai_types.dart';

/// Что именно пошло не так при обращении к провайдеру.
///
/// Различать виды ошибок нужно ради подсказки человеку: «ключ неверный» он исправляет в
/// настройках сборки, «лимит исчерпан» — ждёт или меняет модель, «нет сети» — повторяет
/// запрос, а «что-то ещё» показывает текст провайдера. Одна общая ошибка на все случаи
/// означала бы, что человеку нечего с ней делать.
enum AiErrorKind {
  /// Ключ не принят (`401`, `403`).
  auth,

  /// Лимит запросов или исчерпана квота (`429`).
  rateLimit,

  /// Сеть недоступна, таймаут или обрыв соединения — сам запрос до ответа не дошёл.
  network,

  /// Поток прервал сам человек (кнопка «Стоп»).
  cancelled,

  /// Всё остальное, включая неразобранный ответ провайдера.
  other,
}

/// Ошибка обращения к провайдеру ИИ в том виде, в каком её показывает экран.
///
/// Провайдер переводит сюда свои исключения (`DioException` и прочее): экран не должен знать
/// ни про HTTP-клиент, ни про формат ошибок конкретного API. Текст [message] — готовый к
/// показу, а не технический: причина уже разобрана по [kind].
class AiException implements Exception {
  /// К чему сводится причина — от этого зависит, что предложить человеку.
  final AiErrorKind kind;

  /// Готовая для показа причина на русском.
  final String message;

  /// Ошибка провайдера с разобранной причиной и текстом для человека.
  const AiException(this.kind, this.message);

  /// Текст для логов и отладки: в интерфейс идёт [message], а сюда попадает ещё и вид ошибки.
  @override
  String toString() => 'AiException(${kind.name}): $message';
}

/// Провайдер ИИ: перечисляет доступные модели и отдаёт ответ потоком.
///
/// Прослойка заведена сразу, хотя провайдер в приложении пока один: у xAI/OpenAI, Gemini и
/// Anthropic разные и адреса, и форматы тел запроса, поэтому добавление второго провайдера
/// без такого интерфейса — это переписывание слоя запросов, а не добавление файла.
///
/// Ключ сюда передаёт вызывающий: провайдер не знает, откуда ключ взялся (в сборке он
/// вшит через `--dart-define`, см. `ai_keys.dart`), и не хранит его у себя.
abstract class AiProvider {
  /// Список моделей, доступных этому ключу, — в порядке, в каком его отдал провайдер.
  ///
  /// Бросает [AiException] с разобранной причиной: недоступный ключ и отсутствие сети —
  /// разные ситуации, и на экране они выглядят по-разному.
  Future<List<AiModel>> listModels();

  /// Ответ модели потоком: текст, «размышления» и расход токенов приходят по мере генерации.
  ///
  /// [messages] — вся переписка, включая системную часть: API провайдеров не хранят контекст
  /// между запросами, каждый запрос несёт историю целиком. Прерывание потока (человек нажал
  /// «Стоп» или ушёл с экрана) обязано рвать и HTTP-запрос — иначе соединение останется
  /// висеть до конца генерации, а токены всё это время будут списываться.
  ///
  /// Бросает [AiException] — в том числе уже после того, как первые чанки пришли.
  Stream<AiChunk> stream({
    required String model,
    required List<AiMessage> messages,
  });
}
