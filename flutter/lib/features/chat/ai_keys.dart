/// Ключи провайдеров ИИ, вшитые в сборку.
///
/// Ключ приходит в сборку значением `--dart-define=GROK_API_KEY=…` (см. `.github/workflows/
/// android.yml` и `macos.yml`, где значение берётся из секретов репозитория), поэтому в
/// репозитории ключа нет и в исходниках он не встречается. Локальный запуск без ключа ничего
/// не сломает — чат просто скажет, что ключ в сборке не задан; чтобы проверить чат локально,
/// сборку запускают с тем же define:
///
/// ```
/// flutter run --dart-define=GROK_API_KEY=<ключ>
/// ```
///
/// Принятый риск: значение, вшитое в APK, из этого APK извлекается. Для личной сборки, которую
/// ставят себе на телефон, это осознанный обмен — иначе ключ пришлось бы вводить руками на
/// каждом устройстве. Если сборка когда-нибудь станет публичной, ключ придётся убрать из неё
/// и вернуть ввод ключа в интерфейсе.
class AiKeys {
  /// Значение, вшитое в сборку на этапе компиляции.
  ///
  /// Обязательно `const`: `String.fromEnvironment` подставляет значение только при константном
  /// вычислении, и в неконстантном виде всегда возвращает пустую строку.
  static const String _grok = String.fromEnvironment('GROK_API_KEY');

  /// Ключ xAI (Grok) или пустая строка, если в этой сборке его не задавали.
  ///
  /// Пробелы по краям срезаем: ключ подставляют из секрета, а лишний пробел в заголовке
  /// `Authorization` — это `401`, причину которого искать долго.
  static String get grok => _grok.trim();

  /// Задан ли ключ xAI в этой сборке.
  ///
  /// Экран чата по этому признаку решает, показывать поле ввода или подсказку о том, что
  /// ключ надо задать при сборке: запрос без ключа вернул бы `401`, и человек искал бы
  /// причину в чате, а не в сборке.
  static bool get hasGrok => grok.isNotEmpty;
}
