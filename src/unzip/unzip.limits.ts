/**
 * Лимиты распаковки. Своим модулем, а не в src/config/env.ts: env.ts — общий файл конфига
 * (его правит владелец конфига), а эти значения нужны только распаковке. Читаются из
 * окружения с дефолтами, как и остальные лимиты проекта.
 *
 * Зачем они вообще: архив — единственная ручка, где пользовательский файл заставляет сервер
 * писать данные, объём которых задаёт сам файл. Без потолков zip-бомба (миллионы записей,
 * гигабайты распакованного из мегабайта) роняет процесс по памяти, а так как `onModuleInit`
 * возвращает незавершённые задачи в очередь, получается crash-loop: API недоступен всем,
 * пока кто-нибудь вручную не удалит строку UnzipJob. Проверки идут по центральному каталогу
 * ДО распаковки, то есть бомба отсекается без чтения байтов.
 *
 * Все переменные нужно внести в .env.example (нулевые значения не предусмотрены: лимит —
 * это защита, а не настройка вкуса).
 */

/** Число из окружения с дефолтом; мусор и неположительные значения читаются как дефолт. */
function limit(name: string, def: number): number {
  const raw = process.env[name];
  if (raw === undefined || raw === '') return def;
  const value = Number(raw);
  if (!Number.isFinite(value) || value <= 0) return def;
  return Math.floor(value);
}

/**
 * Сколько записей центрального каталога готовы принять (UNZIP_MAX_ENTRIES).
 * 20 000 — с запасом на реальные выгрузки (Google Takeout по 10-20 тысяч файлов бывает)
 * и на порядок меньше того, что помещается в мусорном каталоге.
 */
export const UNZIP_MAX_ENTRIES = limit('UNZIP_MAX_ENTRIES', 20_000);

/**
 * Потолок суммарного распакованного объёма одной задачи (UNZIP_MAX_TOTAL_MB, по умолчанию
 * 100 ГиБ). Считается по центральному каталогу: сюда упирается и «архив на 50 ГиБ, который
 * разворачивается в 50 ГиБ», и дедуп-трафик в бакет. Квот на пользователя в проекте нет,
 * поэтому потолок общий.
 */
export const UNZIP_MAX_TOTAL_BYTES = limit('UNZIP_MAX_TOTAL_MB', 102_400) * 1024 * 1024;

/**
 * Во сколько раз распакованное может превышать сам архив (UNZIP_MAX_RATIO).
 * Легитимные архивы фото/видео (уже сжатые данные) дают ~1, архивы текстов — десятки;
 * 200 отсекает бомбы, не задевая ни то, ни другое.
 */
export const UNZIP_MAX_RATIO = limit('UNZIP_MAX_RATIO', 200);

/**
 * Коэффициент сжатия одного члена архива (UNZIP_MAX_ENTRY_RATIO). Проверяется на каждом
 * файле: суммарный коэффициент можно удержать под потолком одной безобидной частью архива,
 * а один член с коэффициентом 10 000 — это гигабайты трафика и минуты CPU на ровном месте.
 * Такой член пропускается (остальные распаковываются), а не валит задачу.
 */
export const UNZIP_MAX_ENTRY_RATIO = limit('UNZIP_MAX_ENTRY_RATIO', 1000);

/** Глубина пути внутри архива, сегментов (UNZIP_MAX_DEPTH). 32 — как у большинства распаковщиков. */
export const UNZIP_MAX_DEPTH = limit('UNZIP_MAX_DEPTH', 32);

/** Сколько папок может создать одна задача (UNZIP_MAX_FOLDERS): `a/a/a/...` из архива иначе плодит уровни бесконечно. */
export const UNZIP_MAX_FOLDERS = limit('UNZIP_MAX_FOLDERS', 10_000);

/**
 * Файлы до этого размера распаковываются в память одним проходом (UNZIP_BUFFER_LIMIT_MB).
 * 64 МБ, а не 128: в памяти живёт и буфер, и `Buffer.concat` (то есть вдвое больше), а у
 * процесса API потолок 600 МБ (`max_memory_restart` в deploy/pm2/ecosystem.config.cjs).
 * Крупнее — потоком, и это ровно один проход (см. hashTee).
 */
export const UNZIP_BUFFER_LIMIT = limit('UNZIP_BUFFER_LIMIT_MB', 64) * 1024 * 1024;

/**
 * Сколько раз подряд задачу можно вернуть в очередь после внезапного перезапуска процесса
 * (UNZIP_MAX_RESTARTS). Один-два раза нужно честно: деплой или падение по памяти убивают
 * процесс на середине длинной распаковки, а она идемпотентна и продолжается с чекпойнта.
 * Но если задача валит процесс снова и снова, её надо снять, а не гонять по кругу.
 */
export const UNZIP_MAX_RESTARTS = limit('UNZIP_MAX_RESTARTS', 2);
