// Зоны файлового дерева:
// FILES  — обычный диск: любой файл хранится как есть, конвертация медиа НЕ выполняется,
//          в раздел «Фото» (лента по месяцам) не попадает.
// PHOTOS — поддерево системной папки «Фото»: фото/видео конвертируются (мастер + превью),
//          попадают в таймлайн и альбомы.
export const ZONE_FILES = 'FILES';
export const ZONE_PHOTOS = 'PHOTOS';
export type Zone = typeof ZONE_FILES | typeof ZONE_PHOTOS;

/** Имя системной папки-медиатеки верхнего уровня (ребёнок корня пользователя). */
export const PHOTO_FOLDER_NAME = 'Фото';

/**
 * Имя легаси-папки «Телефон» (общий на все телефоны корень зеркала). Сервер её больше
 * не заводит и не защищает от удаления: корень зеркала свой у каждого устройства
 * (ApiToken.mirrorFolderId). Существующая папка продолжает работать — её id по-прежнему
 * отдаётся в `GET /auth/me` (`phoneFolderId`), поэтому имя остаётся как историческая справка.
 */
export const PHONE_FOLDER_NAME = 'Телефон';

/**
 * Корень зеркала устройства — папка «<Имя устройства> - Файлы» прямо в корне пользователя
 * (ребёнок users.rootFolderId), а не внутри «Телефон»: корень у каждого устройства свой, а
 * общий на всех означал бы, что удаление файла на одном телефоне уносит файлы другого.
 */
export const MIRROR_FOLDER_SUFFIX = ' - Файлы';

/** Запасное имя для токена с пустым label, иначе папка называлась бы « - Файлы». */
const MIRROR_FOLDER_FALLBACK = 'Устройство';

/**
 * Имя корня зеркала устройства по его label. Это только подпись: корень адресуется по id
 * из токена, поэтому одинаковые label не дают общего корня — второе устройство получает
 * свободное имя с уточнением «(2)» (см. AuthService.deviceMirrorFolderId).
 */
export function mirrorFolderName(label: string): string {
  const clean = String(label ?? '').trim();
  return `${clean || MIRROR_FOLDER_FALLBACK}${MIRROR_FOLDER_SUFFIX}`;
}
