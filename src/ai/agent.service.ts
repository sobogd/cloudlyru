import { Injectable, Logger } from '@nestjs/common';
import { env } from '../config/env';

/** Что вернул прогон агента: добытый текст и причина, по которой его нет. */
export interface AgentOutcome {
  /** Отчёт агента — то, что он прочитал на экране телефона. Пусто, если прогон не удался. */
  report: string;
  /** Сколько шагов сделал агент: уходит в лог, человеку не показывается. */
  steps: number;
}

/**
 * Агент на телефоне: управляет Android по ADB и выполняет в браузере то, что попросили.
 *
 * Зачем отдельный сервис вместо поиска: поиск (`SearchService`) отдаёт список ссылок и сниппетов,
 * а он не поможет там, где нужен сам сайт — войти, нажать, дочитать. Агент делает это шагами по
 * экрану: открывает Chrome, набирает запрос, читает выдачу и возвращает текст.
 *
 * Где он живёт и почему: сам цикл — это питон на маке (`agents/android-agent/server.py`), потому
 * что телефон подключён по USB именно к маку. Сюда он приходит через тот же reverse-SSH туннель,
 * что модель и поиск, и точно так же доступен только с самого сервера.
 *
 * Цена этой возможности — время: прогон идёт десятками секунд, а то и минутами (каждый шаг —
 * запрос к модели на маке и чтение экрана телефона), и телефон при этом один, поэтому второй
 * запрос получает «занято». Поэтому режим агента в чате включается кнопкой, а не сам по себе:
 * человек сам решает, когда готов ждать.
 *
 * Ищет агент не по сниппетам выдачи, а по источникам: он обязан открыть и прочитать не меньше
 * пяти разных страниц, прежде чем ему разрешат ответить (`MIN_PAGES` в `agent.py`). Ответ по
 * заголовкам выдачи — это пересказ чужих сниппетов, ради чего режим и не нужен.
 */
@Injectable()
export class AgentService {
  private readonly logger = new Logger(AgentService.name);

  /**
   * Сколько шагов разрешаем агенту.
   *
   * Тридцать — это «поиск, пять прочитанных страниц и возврат к выдаче»: агент обязан открыть не
   * меньше пяти источников (иначе он отвечает по сниппетам выдачи, ради чего режим и не нужен), и
   * на одну страницу уходит три-четыре шага. Меньше двадцати пяти ставить нельзя: прогон упрётся
   * в лимит, не дойдя до последнего источника.
   */
  private readonly maxSteps = 30;

  /**
   * Сколько ждём прогон целиком, мс.
   *
   * Потолок с запасом к самому худшему случаю: тридцать шагов по 25 секунд — это двенадцать
   * минут. Обрывать раньше нельзя: оборванный по таймауту запрос оставит телефон в середине
   * работы, а результат потеряется. Истёк — считаем прогон неудачным и говорим об этом в чате.
   */
  private readonly timeoutMs = 900_000;

  /** Задан ли адрес агента. Пусто — режим агента недоступен. */
  get configured(): boolean {
    return env.AGENT_URL.trim().length > 0;
  }

  /**
   * Прогнать [task] на телефоне и вернуть отчёт агента.
   *
   * [signal] рвёт ожидание, если человек ушёл с экрана или нажал «Стоп»: сервер перестаёт ждать
   * ответа с мака. Сам прогон на телефоне при этом доводится до конца — у агента нет отмены
   * (он работает шагами по чужому экрану, и бросить его на середине значит оставить телефон в
   * непонятном состоянии), поэтому следующий запрос в это время получит «занято».
   *
   * Бросает `AgentError` — в отличие от поиска, ошибку агента не глотаем: поиск подмешивает
   * свежие данные, без него ответ просто беднее, а агент — это и есть весь запрос человека,
   * и молча ответить без него значит соврать. Контроллер превращает ошибку в событие потока.
   */
  async run(task: string, signal?: AbortSignal): Promise<AgentOutcome> {
    if (!this.configured) {
      throw new AgentError('агент выключен на сервере', 'agent_disabled');
    }
    const url = `${env.AGENT_URL.trim().replace(/\/+$/, '')}/run`;
    const started = Date.now();
    this.logger.log(`агент: задача ${task.length} симв. уходит на мак`);
    try {
      const res = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ task, max_steps: this.maxSteps }),
        // Два условия обрыва складываются по «кто раньше»: свой потолок на весь прогон и разрыв
        // со стороны клиента.
        signal: AbortSignal.any([AbortSignal.timeout(this.timeoutMs), ...(signal ? [signal] : [])]),
      });
      // Тело разбираем в любом случае: причина отказа приходит и с не-200, и в ней готовая
      // фраза для человека (`no_device`, `busy`) — её показываем в чате как есть.
      const data = (await res.json().catch(() => null)) as Record<string, unknown> | null;
      const report = typeof data?.answer === 'string' ? data.answer.trim() : '';
      if (!res.ok || !report) {
        const code = typeof data?.error === 'string' ? data.error : `agent_http_${res.status}`;
        const message = typeof data?.message === 'string' ? data.message : '';
        this.logger.warn(`агент: отказ (${code}) за ${Date.now() - started} мс${message ? ` — ${message}` : ''}`);
        throw new AgentError(message || reasonText(code), code);
      }
      const steps = typeof data?.steps === 'number' ? data.steps : 0;
      this.logger.log(
        `агент: отчёт ${report.length} симв. за ${steps} шагов, ${Date.now() - started} мс`,
      );
      return { report, steps };
    } catch (e) {
      if (e instanceof AgentError) throw e;
      // Таймаут, обрыв туннеля, мак спит, сервис не запущен — для человека это одно и то же:
      // агент не отработал. Причину пишем в лог, она же уходит в чат короткой фразой.
      const reason = e instanceof Error ? e.message : String(e);
      this.logger.warn(`агент: недоступен — ${reason} (${Date.now() - started} мс)`);
      throw new AgentError('агент не отвечает: проверь мак и туннель', 'agent_unavailable');
    }
  }
}

/**
 * Отказ агента с причиной, пригодной для показа человеку.
 *
 * Отдельный тип, а не HttpException: сервис не знает, в каком виде ошибка уйдёт наружу — здесь
 * это всегда событие внутри уже начатого потока SSE, и решение принимает контроллер.
 */
export class AgentError extends Error {
  constructor(
    message: string,
    /** Код причины: `no_device`, `busy`, `agent_unavailable` и подобные. */
    readonly code: string,
  ) {
    super(message);
    this.name = 'AgentError';
  }
}

/**
 * Фраза для человека по коду причины с мака.
 *
 * Нужна на случай, когда сервис отказал без текста (свой код ошибки, старый ответ): код в чате
 * ничего не объясняет, а показать человеку нужно именно причину.
 */
function reasonText(code: string): string {
  switch (code) {
    case 'no_device':
      return 'телефон не подключён к маку по USB — агент работать не может';
    case 'busy':
      return 'телефон занят другой задачей — дождись её окончания';
    case 'too_long':
      return 'вопрос слишком длинный для агента';
    default:
      return 'агент не смог выполнить задачу';
  }
}
