import type { SearchResult } from './search.service';

/**
 * Системная часть запроса к модели: кто отвечает, как отвечает и что помнит о владельце.
 *
 * Здесь, а не в приложении, по той же причине, что и адрес модели: запрос делает сервер.
 * Подсказка уходит в каждый запрос, а на маке вход стоит временем, а не деньгами: префилл идёт
 * около 300 токенов в секунду, поэтому формулировки короткие, а не развёрнутые.
 */

/** Кто отвечает. */
const ROLE =
  'Ты — помощник в приложении CloudlyRu (личное облако файлов владельца). Отвечай на языке вопроса.';

/**
 * Манера речи: коротко, по-человечески, без «слопа».
 *
 * Запреты перечислены поштучно: общая просьба «пиши кратко» на привычки модели не влияет.
 * Отдельно сказано, что краткость не отменяет смысла — иначе ответ сжимается до бесполезного.
 *
 * Список длиннее, чем нужен сильной модели, и это осознанно: Gemma 4 E4B держит инструкции
 * заметно хуже, чем модель на сотни миллиардов параметров, и без прямого запрета на список
 * отвечает списком там, где хватает абзаца.
 */
const STYLE =
  'Пиши коротко и человеческим языком, рубленые фразы допустимы. Запрещено: вступления и ' +
  'анонсы, пересказ сказанного в конце, похвала вопроса, оговорки на пол-абзаца, списки там, ' +
  'где хватает абзаца, штампы («важно отметить», «в современном мире»), длинное тире. ' +
  'Не повторяй вопрос — отвечай сразу. Без подробностей ответ бесполезен — дай их, но без обвязки.';

/**
 * Запрет додумывать контекст владельца.
 *
 * Появился после живого случая: на вопрос о курсе биткоина модель приписала цену в рублях —
 * только потому, что разговор шёл по-русски. Язык вопроса не говорит ни о стране, ни о валюте.
 */
const NO_GUESSING =
  'Не додумывай то, чего владелец не говорил: страну, город, валюту, работу. Язык вопроса об ' +
  'этом не говорит. Валюту источника не пересчитывай без просьбы. Не знаешь — скажи одной фразой.';

/** Точность: короткая манера речи не повод менять числа и имена. */
const ACCURACY = 'Числа, имена, даты, код и ссылки передавай точно, как есть.';

/** Собирает системную подсказку; [memory] — свободный текст владельца о себе (может быть пустым). */
export function systemPrompt(memory: string): string {
  const parts = [ROLE, STYLE, NO_GUESSING, ACCURACY];
  const trimmed = memory.trim();
  if (trimmed) {
    // Память идёт последней и с пометкой: она уточняет всё, что сказано выше («я в Испании»
    // снимает запрет догадок именно для этого случая), поэтому её место в конце.
    parts.push(`Что владелец рассказал о себе (учитывай как факт):\n${trimmed}`);
  }
  return parts.join(' ');
}

/**
 * Нужен ли вопросу поиск в интернете — по самому тексту вопроса.
 *
 * Это решение «за человека», поэтому правило намеренно узкое: ищем только там, где ответ почти
 * наверняка зависит от сегодняшнего дня. Ошибиться в другую сторону (не поискать) дешевле и
 * безопаснее: модель ответит по своим знаниям и скажет, если их не хватает, — тогда вопрос можно
 * задать заново с явным «искать».
 *
 * Признаки: свежие события и новости, текущие величины (курс, погода, цена), прямые указания на
 * время («сегодня», «сейчас», «последние»), а также годы, начиная с прошлого, — про них модель
 * без поиска знает только до своего среза знаний (у Gemma 4 это январь 2025).
 */
export function needsSearch(question: string): boolean {
  const text = question.toLowerCase();
  const patterns = [
    'сегодня',
    'сейчас',
    'вчера',
    'завтра',
    'только что',
    'новост',
    'последн',
    'актуальн',
    'свеж',
    'курс',
    'котировк',
    'погод',
    'сколько стоит',
    'цена',
    'стоимость',
    'что нового',
    'что случилось',
    'который час',
    'текущ',
  ];
  if (patterns.some((p) => text.includes(p))) return true;
  // годы: всё, что не старше прошлого, модель без поиска знает лишь до своего среза
  const currentYear = new Date().getFullYear();
  for (let year = currentYear - 1; year <= currentYear + 1; year++) {
    if (text.includes(String(year))) return true;
  }
  return false;
}

/**
 * Блок с результатами поиска, который подмешивается в вопрос.
 *
 * Отдельной функцией, а не частью системной подсказки: это данные, а не правила поведения, и
 * их место рядом с вопросом — модель видит свежие сведения прямо перед тем, как отвечать.
 * Сниппеты обрезаются: у Gemma 4 контекст в 128k токенов, но префилл на маке линейный по
 * времени, и десять длинных выжимок стоят лишних секунд ожидания.
 *
 * Дата в заголовке нужна потому, что по ней модель понимает, «свежие» ли это данные: без неё
 * она может решить, что сведения устарели, и отказаться отвечать.
 */
export function searchBlock(results: SearchResult[], now = new Date()): string {
  const date = now.toLocaleDateString('ru-RU', { day: '2-digit', month: '2-digit', year: 'numeric' });
  const lines = results.map((r, i) => {
    const snippet = r.snippet.replace(/\s+/g, ' ').slice(0, 400);
    return `${i + 1}. ${r.title} — ${r.url}\n   ${snippet}`;
  });
  return (
    `Результаты поиска в интернете (получены ${date}):\n${lines.join('\n')}\n\n` +
    'Основа ответа — эти результаты. Если ответа в них нет, скажи одной фразой, что не нашёл, ' +
    'и не выдумывай. Ссылки давай точно, как в списке. Не пересказывай список целиком.'
  );
}

/**
 * Подсказка для сжатия разговора (компакция контекста).
 *
 * Это реплика человека, а не системная роль: с инструкцией в `system` Gemma 4 возвращает один
 * токен и пустой текст (замер), а с той же инструкцией после переписки — нормальную выжимку.
 * Поэтому текст написан как просьба, обращённая к тому, кто только что прочитал разговор.
 *
 * Просим сохранить именно то, что человек заметит пропавшим в следующем ответе: суть, факты,
 * имена, числа и незакрытые вопросы. Отдельно запрещено обращаться к читателю и «продолжать
 * разговор» — модель с радостью отвечает вместо того, чтобы сжимать, и такая выжимка в
 * следующем запросе выглядит как ответ, которого никто не задавал.
 */
export const COMPACT_PROMPT =
  'Сожми нашу переписку выше в короткую выжимку: она заменит её целиком в следующих ответах. ' +
  'Сохрани всё, что понадобится дальше: о чём говорили, что решили, факты, имена, числа, ' +
  'ссылки и незакрытые вопросы. Пиши по-русски, сжато, без вступлений. Не отвечай на вопросы ' +
  'из переписки, не обращайся к читателю, не продолжай разговор — только выжимка.';

