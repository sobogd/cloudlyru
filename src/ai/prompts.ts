/**
 * Системная часть запроса к модели: кто отвечает, как отвечает и что помнит о владельце.
 *
 * Здесь, а не в приложении, по той же причине, что и ключ провайдера: запрос делает сервер.
 * Размер подсказки — это деньги: она уходит в каждый запрос, поэтому формулировки короткие,
 * а не развёрнутые (прежняя версия занимала 1041 символ ≈ 473 токена на каждый запрос).
 */

/** Кто отвечает. */
const ROLE =
  'Ты — помощник в приложении CloudlyRu (личное облако файлов владельца). Отвечай на языке вопроса.';

/**
 * Манера речи: коротко, по-человечески, без «слопа».
 *
 * Запреты перечислены поштучно: общая просьба «пиши кратко» на привычки модели не влияет.
 * Отдельно сказано, что краткость не отменяет смысла — иначе ответ сжимается до бесполезного.
 */
const STYLE =
  'Пиши коротко и человеческим языком, рубленые фразы допустимы. Запрещено: вступления и ' +
  'анонсы, пересказ сказанного в конце, похвала вопроса, оговорки на пол-абзаца, списки там, ' +
  'где хватает абзаца, штампы («важно отметить», «в современном мире»), длинное тире. ' +
  'Не повторяй вопрос — отвечай сразу. Без подробностей ответ бесполезен — дай их, но без обвязки.';

/**
 * Запрет додумывать контекст владельца.
 *
 * Появился после живого случая: на вопрос о курсе биткоина модель приписала цену в рублях —
 * только потому, что разговор шёл по-русски. Язык вопроса не говорит ни о стране, ни о валюте.
 */
const NO_GUESSING =
  'Не додумывай то, чего владелец не говорил: страну, город, валюту, работу. Язык вопроса об ' +
  'этом не говорит. Валюту источника не пересчитывай без просьбы. Не знаешь — скажи одной фразой.';

/** Точность: короткая манера речи не повод менять числа и имена. */
const ACCURACY = 'Числа, имена, даты, код и ссылки передавай точно, как есть.';

/**
 * Про поиск: он стоит денег (каждый вызов $0.005 плюс десятки тысяч токенов на страницы),
 * поэтому просим модель не искать «на всякий случай».
 *
 * Параметром число поисков у xAI не ограничить: у инструмента в Responses API есть только
 * фильтры доменов и работа с картинками. Остаётся просьба в подсказке.
 */
const SEARCH_HINT =
  'Ищи в интернете только если ответ зависит от свежих данных. Хватит одного поиска: ' +
  'повторные вызовы без новой нужды не делай.';

/** Собирает системную подсказку; [memory] — свободный текст владельца о себе (может быть пустым). */
export function systemPrompt(memory: string, search: boolean): string {
  const parts = [ROLE, STYLE, NO_GUESSING, ACCURACY];
  if (search) parts.push(SEARCH_HINT);
  const trimmed = memory.trim();
  if (trimmed) {
    // Память идёт последней и с пометкой: она уточняет всё, что сказано выше («я в Испании»
    // снимает запрет догадок именно для этого случая), поэтому её место в конце.
    parts.push(`Что владелец рассказал о себе (учитывай как факт):\n${trimmed}`);
  }
  return parts.join(' ');
}

/**
 * Нужен ли вопросу поиск в интернете — по самому тексту вопроса.
 *
 * Это решение «за человека», поэтому правило намеренно узкое: ищем только там, где ответ почти
 * наверняка зависит от сегодняшнего дня. Ошибиться в другую сторону (не поискать) дешевле и
 * безопаснее: модель ответит по своим знаниям и скажет, если их не хватает, — тогда вопрос можно
 * задать заново с явным «искать».
 *
 * Признаки: свежие события и новости, текущие величины (курс, погода, цена), прямые указания на
 * время («сегодня», «сейчас», «последние»), а также годы, начиная с прошлого, — про них модель
 * без поиска знает только до своего среза знаний.
 */
export function needsSearch(question: string): boolean {
  const text = question.toLowerCase();
  const patterns = [
    'сегодня',
    'сейчас',
    'вчера',
    'завтра',
    'только что',
    'новост',
    'последн',
    'актуальн',
    'свеж',
    'курс',
    'котировк',
    'погод',
    'сколько стоит',
    'цена',
    'стоимость',
    'что нового',
    'что случилось',
    'который час',
    'текущ',
  ];
  if (patterns.some((p) => text.includes(p))) return true;
  // годы: всё, что не старше прошлого, модель без поиска знает лишь до своего среза
  const currentYear = new Date().getFullYear();
  for (let year = currentYear - 1; year <= currentYear + 1; year++) {
    if (text.includes(String(year))) return true;
  }
  return false;
}
