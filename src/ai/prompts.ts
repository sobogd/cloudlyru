/**
 * Стили ответа: предустановки системной подсказки.
 *
 * Зачем это на сервере, а не в приложении: подсказка — часть запроса к модели, а запросы делает
 * сервер. Заодно список стилей один на все клиенты, и подпись стиля в интерфейсе не разъедется
 * с тем, что реально уходит модели.
 *
 * Стиль выбирается на чат и хранится в `ai_chats.style` (`prisma/migrations/20260918140000_ai_chat`
 * завела саму таблицу, отдельная миграция добавила колонку). Новый чат наследует стиль
 * последнего выбора — человеку не приходится ставить его заново в каждом разговоре.
 */

/** Идентификатор стиля ответа. */
export type AiStyleId = 'normal' | 'caveman' | 'humanizer';

/** Общая часть подсказки: кто отвечает и в каком приложении. */
const ROLE =
  'Ты — помощник внутри приложения CloudlyRu (личное облако файлов и фото владельца). ' +
  'Отвечай на языке вопроса.';

/**
 * Постоянное требование к точности, одинаковое для всех стилей.
 *
 * Нужно потому, что стили меняют манеру речи, и модель легко начинает «играть роль» за счёт
 * фактов: пещерным языком перевирает числа, а «по-человечески» — додумывает. Стиль речи не
 * повод терять точность, поэтому это сказано отдельной строкой в каждом стиле.
 */
const ACCURACY =
  'Факты, числа, имена, код и ссылки передавай точно, как есть: манера речи не повод их менять.';

/**
 * Подсказки по стилям.
 *
 * `normal` — обычный ассистент; `caveman` — рубленый «пещерный» язык; `humanizer` — живой
 * человеческий текст без штампов ИИ. Требования в `humanizer` намеренно конкретные (запрет
 * списков ради списков, длинного тире, итогового пересказа): общая просьба «пиши естественно»
 * на такие привычки модели не влияет.
 */
const STYLES: Record<AiStyleId, { title: string; hint: string; prompt: string }> = {
  normal: {
    title: 'Обычный',
    hint: 'Как есть: по делу, без вступлений',
    prompt: 'Отвечай по делу, без лишних вступлений и выводов ради объёма.',
  },
  caveman: {
    title: 'Кейвман',
    hint: 'Пещерный язык: коротко и просто',
    prompt:
      'Пиши как пещерный человек: короткие рубленые фразы, простые слова, без вежливостей, ' +
      'вступлений и обращений. Многоточие вместо связок можно. Смысл сохраняй целиком: ' +
      'каменная речь — не повод потерять половину ответа или сделать его непонятным.',
  },
  humanizer: {
    title: 'Хуманайзер',
    hint: 'Живой текст без штампов ИИ',
    prompt:
      'Пиши как живой человек: предложения разной длины, обычные слова. Не используй штампы ' +
      'ИИ («важно отметить», «в современном мире», «давайте разберёмся», «в заключение»), ' +
      'не превращай ответ в список, если хватает абзаца, не подлизывайся и не хвали вопрос, ' +
      'не пересказывай сказанное в конце. Длинное тире не используй. Если чего-то не знаешь ' +
      '— скажи прямо, без оговорок на пол-абзаца.',
  },
};

/** Стиль по умолчанию — тот, что стоит у чата без выбранного стиля и у старых чатов. */
export const DEFAULT_AI_STYLE: AiStyleId = 'normal';

/** Стиль, которым отвечает чат: известный идентификатор или стиль по умолчанию. */
export function normalizeStyle(value: unknown): AiStyleId {
  return typeof value === 'string' && value in STYLES ? (value as AiStyleId) : DEFAULT_AI_STYLE;
}

/**
 * Список стилей для интерфейса: идентификатор, подпись и короткое пояснение.
 *
 * Отдаётся клиенту ручкой `/ai/styles`, чтобы подписи не дублировались в приложении: список
 * стилей — часть серверной подсказки, а не оформления.
 */
export function styleList(): { id: AiStyleId; title: string; hint: string }[] {
  return (Object.keys(STYLES) as AiStyleId[]).map((id) => ({
    id,
    title: STYLES[id].title,
    hint: STYLES[id].hint,
  }));
}

/** Системная подсказка для запроса: кто отвечает, стиль речи и требование точности. */
export function systemPrompt(style: unknown): string {
  const id = normalizeStyle(style);
  return `${ROLE} ${STYLES[id].prompt} ${ACCURACY}`;
}
