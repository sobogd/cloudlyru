import type { ChatSource } from './websearch.service';

/**
 * Системная часть запроса: правила ответа, память владельца и требование ссылаться на источники.
 *
 * Память приходит от человека (экран «Память») и подмешивается сюда, а не в вопрос: так модель
 * видит её в каждом запросе, но в истории чата она не повторяется десятки раз.
 */
export function systemPrompt(memory: string): string {
  const rules = [
    'Ты помощник в приложении Cloudly. Отвечай на языке вопроса, коротко и по делу.',
    'Если в запросе есть «Источники из интернета», опирайся на их текст, а не на свои знания: ' +
      'данные могли устареть. После каждого утверждения из источника ставь его номер в квадратных ' +
      'скобках: [1], [2].',
    'Если в источниках ответа нет — скажи это одной фразой и не выдумывай. Ссылки давай только ' +
      'те, что есть в источниках.',
    'Числа, имена, даты и названия переноси точно, как они написаны в источнике.',
  ];
  const parts = [rules.join('\n')];
  if (memory.trim()) {
    parts.push(`Что владелец просил помнить о себе и о стиле ответов:\n${memory.trim()}`);
  }
  return parts.join('\n\n');
}

/**
 * Блок с источниками, который подмешивается в вопрос.
 *
 * Нумерация здесь и есть та самая, которой потом пользуются ссылки на экране: модель ставит
 * `[1]` в тексте, приложение по этому номеру достаёт адрес из сохранённых источников. Поэтому
 * порядок менять нельзя — он идёт от поисковой выдачи.
 */
export function sourcesBlock(sources: ChatSource[], note: string | null, now = new Date()): string {
  const stamp = now.toLocaleString('ru-RU', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
  const lines: string[] = [`Источники из интернета (получены ${stamp}):`];
  for (const source of sources) {
    lines.push('');
    lines.push(`[${source.position}] ${source.title} — ${source.url}`);
    if (source.read) {
      lines.push(source.text);
    } else {
      // Страницу открыть не удалось: отдаём выдержку из выдачи и прямо говорим, что это она.
      lines.push(`Выдержка из поисковой выдачи (страница не открылась): ${source.snippet}`);
    }
  }
  if (note) {
    lines.push('');
    lines.push(note);
  }
  lines.push('');
  lines.push('Ссылайся на источники номерами в квадратных скобках. Если ответа в них нет — скажи это прямо.');
  return lines.join('\n');
}

/**
 * Блок-объяснение, когда поиск был нужен, но данных не принёс.
 *
 * Нужен, чтобы модель не отвечала «не могу» без причины: человек должен видеть, что дело в
 * поиске, а не в её знаниях.
 */
export function searchFailedBlock(note: string | null): string {
  const reason = note ?? 'Поиск в интернете не дал результатов.';
  return (
    `${reason}\n\nСвежих данных у тебя нет. Ответь на вопрос своими знаниями, но в первой строке ` +
    'честно скажи, что данные из интернета получить не удалось, и укажи, до какого времени ' +
    'актуальны твои знания.'
  );
}

/**
 * Нужен ли вопросу поиск в интернете — по самому тексту вопроса.
 *
 * Правило сознательно узкое: ошибиться в сторону «не поискать» дешевле, чем искать на каждый
 * чих. Поиск и чтение страниц стоят человеку 5-15 секунд ожидания, поэтому запускается только
 * там, где ответ почти наверняка зависит от свежих данных: прямые просьбы поискать, слова о
 * текущем моменте, деньги и погода, и упоминание свежего года.
 *
 * Клиент может решить иначе: в интерфейсе есть переключатель, и он перебивает это правило в обе
 * стороны — человек видит свой вопрос лучше, чем список слов.
 */
export function needsSearch(question: string, now = new Date()): boolean {
  const text = question.toLowerCase();

  // Прямая просьба — единственный случай, где поиск обязателен независимо от темы.
  const explicit = [
    'поищи',
    'погугли',
    'загугли',
    'найди в интернете',
    'посмотри в интернете',
    'проверь в интернете',
    'что пишут',
    'search',
    'проверь онлайн',
  ];
  if (explicit.some((word) => text.includes(word))) return true;

  // Слова о текущем моменте: без поиска модель отвечает знаниями своего среза обучения.
  const freshness = [
    'сегодня',
    'вчера',
    'сейчас',
    'текущ',
    'последн',
    'свежи',
    'новост',
    'на этой неделе',
    'в этом году',
    'актуальн',
    'на данный момент',
  ];
  if (freshness.some((word) => text.includes(word))) return true;

  // То, что меняется каждый день и что модель помнит только по срезу обучения.
  const volatile = [
    'курс',
    'цена',
    'стоимость',
    'сколько стоит',
    'погода',
    'пробки',
    'котировк',
    'акци',
    'выборы',
    'рейтинг',
    'расписани',
    'дата выхода',
    'обновлени',
  ];
  if (volatile.some((word) => text.includes(word))) return true;

  // Год не старше прошлого: «в 2026 году» модель может знать только из обучения.
  const years = text.match(/\b(19|20)\d{2}\b/g) ?? [];
  return years.some((year) => Number(year) >= now.getFullYear() - 1);
}

