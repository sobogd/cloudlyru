#!/bin/bash
# =============================================================================
# run-llm.sh — keeps the local LLM server (llama.cpp) serving CloudlyRu and pi.
#
# Managed by launchd (com.agent.llm, RunAtLoad + KeepAlive). Replaces run-lmstudio.sh:
# LM Studio снесён целиком, модель считается llama-server'ом прямо с GGUF-файла.
#
# Зачем llama.cpp, а не что-то другое на этом маке: разделу «Чат» и харнессу pi нужен
# вызов инструментов, то есть модель должна уметь просить «открой сайт и введи запрос».
# У mlx-lm разбор вызовов сырой (пустые tool_calls в живых issue), а llama.cpp с --jinja
# разбирает шаблон Qwen штатно. Цена — GGUF вместо MLX и чуть меньшая скорость.
#
# Сервер поднимается с одной моделью (`-m`), а не в режиме роутера. Проверено на этой
# сборке (0.4.1, build 10964): с `--models-dir` сервер не печатает ничего и порт не
# занимает, а с `-m` поднимается за 8 секунд. Модель одна, поэтому роутер и не нужен.
#
# Псевдоним (см. ALIAS ниже) — то имя, под которым модель видна клиентам: в окружении
# сервера CloudlyRu (`LLM_MODEL`), в конфиге переводчика, в уже созданных чатах и в pi. Без
# него llama.cpp назвал бы модель по имени файла (`Qwen3.5-4B-UD-Q4_K_XL`), и приложение
# просило бы несуществующую.
#
# Размышления выключены флагом шаблона. Без этого qwen3.5 уходит в «думание» целиком
# и текста не отдаёт вообще — замер на этой машине: 300 токенов из 300 в reasoning и
# пустой ответ (см. LLM_REASONING в src/config/env.ts). Он же передаётся и в самом запросе
# через LLM_TEMPLATE_KWARGS, чтобы поведение не зависело от того, как поднят сервер.
#
# `--cache-ram 2048` ограничивает кэш промптов двумя гигабайтами. По умолчанию llama.cpp
# разрешает ему расти до 8 ГБ, и на машине с 16 ГБ, где рядом живёт второй движок и
# whisper, это лишний риск: рост RSS с 4,0 до 4,8 ГБ в прошлом запуске был именно им.
#
# Что проверяет сторож: сервер отвечает на /health и в нём есть хотя бы одна модель.
# Догружать модель он не может — в режиме роутера это делает клиент по имени, — но если
# сервер упал, поднимает его заново и пишет об этом одну строку в лог.
# =============================================================================
export PATH="/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin"

LLAMA_SERVER=/opt/homebrew/bin/llama-server
# 4B вместо 9B — замерено на этой машине на реальной задаче (страница ~1100 токенов и два
# вопроса по её содержимому): prefill 344 против 189 ток/с, генерация 33,7 против 19,1,
# оба ответа 10,3 с против 20,3 с. То есть чтение страниц вдвое быстрее, а верность
# ответов та же (обе модели отдали все цифры из текста и ничего не выдумали), и вызовы
# инструментов 4B тоже делает правильно — web_search/fetch_url с осмысленными аргументами.
# Памяти занимает 3,8 ГБ вместо 6,2; освободившиеся два с половиной гигабайта отданы
# TranslateGemma в run-llm-mt.sh, чтобы переводчик жил резидентно рядом.
#
# Историческая справка: до этого был Q6_K, и переход на Q4_K_XL скорости не дал вовсе
# (18,7 против 18,8 ток/с). Причина в архитектуре: Qwen3.5 гибридная (слои линейного
# внимания/Gated DeltaNet) и упирается в вычисления на GPU, а не в загрузку весов, поэтому
# квант, число потоков и тип KV на скорость не влияют. Класс модели — влияет, это и видно
# выше по цифрам.
MODEL="$HOME/models/Qwen3.5-4B-UD-Q4_K_XL.gguf"
# `--alias` — имена, под которыми модель видна клиентам. Их два, и это не запас на будущее:
# `qwen/qwen3.5-9b` зашит в LLM_MODEL сервера CloudlyRu, в конфиге переводчика и в уже
# созданных чатах — имя осталось от 9B, но клиенты продолжают его просить, а llma.cpp,
# встретив незнакомый id, молча отдаёт загруженную модель, то есть ошибка была бы тихой.
# `qwen/qwen3.5-4b` — честное имя текущего файла: под ним модель видят pi и новое
# окружение, и именно его надо указывать в новых конфигах. Оба имени живут одновременно,
# потому что алиас принимает список через запятую: переименование тогда не ломает ни один
# существующий клиент и ни один старый чат.
ALIAS="qwen/qwen3.5-9b,qwen/qwen3.5-4b"
PORT=1234
# 65536 — предел, который эта машина тянет: KV для гибридной модели стоит ~17 КБ на
# токен в q8_0 (полного внимания 8 слоёв из 32, у остальных линейное и KV не растёт), то
# есть 64K — это ~1,14 ГБ против 570 МБ у 32K. Цена не только в памяти: prefill такой длины
# занимает минуты — измерено ~350 ток/с у этой модели, поэтому полное окно читается около
# трёх минут. Полезно там, где нужен большой репозиторий или стопка документов; для диалога
# это лишний расход памяти, которую делит соседний движок перевода.
CTX=65536
LOG=/tmp/llm-server.log
CHECK_EVERY=30

# Прошлое состояние — чтобы писать в лог только переходы, а не строку каждые 30 секунд.
state=""

say() {
  echo "$(date '+%Y-%m-%d %H:%M:%S') $*"
}

server_ok() {
  # Именно llama-server, а не «кто-то на этом порту»: его /health отдаёт {"status":"ok"}.
  # Проверка по одному коду ответа обманулась бы чужим сервером — так и вышло при переезде:
  # на порту ещё жил LM Studio, на /health он отвечал ошибкой в теле с кодом 200, и сторож
  # считал, что всё хорошо, хотя llama-server не поднялся вовсе.
  curl -sf -m 5 "http://127.0.0.1:${PORT}/health" 2>/dev/null | grep -q '"status":"ok"'
}

start_server() {
  # Логи сервера идут в отдельный файл: launchd пишет сюда только переходы состояния.
  nohup "$LLAMA_SERVER" \
    -m "$MODEL" --alias "$ALIAS" \
    --host 127.0.0.1 --port "$PORT" \
    --jinja \
    -ngl 999 \
    -c "$CTX" \
    --flash-attn on \
    --cache-type-k q8_0 --cache-type-v q8_0 \
    --cache-ram 2048 \
    --chat-template-kwargs '{"enable_thinking":false}' \
    >>"$LOG" 2>&1 &
  say "llama-server запущен (pid $!), лог: $LOG"
}

if [ ! -x "$LLAMA_SERVER" ]; then
  say "нет $LLAMA_SERVER — поставь llama.cpp: brew install llama.cpp"
  exit 1
fi
if [ ! -f "$MODEL" ]; then
  say "нет файла модели $MODEL — скачай GGUF в $HOME/models"
  exit 1
fi

while :; do
  if ! server_ok; then
    # Сервера нет или он не отвечает. Убиваем возможный подвисший процесс, чтобы не
    # плодить слушателей на одном порту: порт занят мёртвым процессом — классическая
    # причина «перезапустил, а всё равно не отвечает».
    pkill -f "llama-server.*--port ${PORT}" 2>/dev/null
    sleep 1
    start_server
    for _ in $(seq 1 20); do
      server_ok && break
      sleep 1.5
    done
  fi

  now=down
  if server_ok; then
    # Моделей может быть ноль: роутер поднимает их по запросу клиента. Это не «down»,
    # иначе сторож перезапускал бы сервер каждые полминуты на пустом каталоге.
    now=up
  fi
  [ "$now" != "$state" ] && say "состояние: ${now}"
  state="$now"

  sleep "$CHECK_EVERY"
done
